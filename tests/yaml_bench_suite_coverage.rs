/// The out-of-scope assertions are negative — they pass when nothing is found,
/// which is also what a broken detector does. This pins that each one actually
/// fires on input containing the construct.
#[test]
fn detector_finds_every_feature_it_claims_to() {
    let cases: &[(Feature, &str)] = &[
        (Feature::FlowMapping, "a: {k: v}\n"),
        (Feature::FlowSequence, "a: [1, 2]\n"),
        (Feature::Anchor, "a: &anc\n  k: v\n"),
        (Feature::Alias, "a: &anc\n  k: v\nb: *anc\n"),
        (Feature::LiteralBlockScalar, "a: |\n  text\n"),
        (Feature::FoldedBlockScalar, "a: >\n  text\n"),
        (Feature::ExplicitKey, "? key\n: value\n"),
        (Feature::MultiDocument, "---\na: 1\n---\nb: 2\n"),
        (Feature::MergeKey, "base: &b\n  a: 1\nc:\n  <<: *b\n"),
    ];

    for (feature, yaml) in cases {
        let found = features_of("self-test", yaml.as_bytes());
        assert!(
            found.contains(feature),
            "detector missed {} in:\n{yaml}",
            feature.name()
        );
    }

    // Tags never reach the index — the parser rejects them — so the tag check
    // is text-based and is pinned separately.
    assert!(
        YamlIndex::build(b"a: !!str 1\n").is_err(),
        "tags now parse; the Tag detection here needs to move to the index"
    );
}

#[test]
fn every_supported_feature_is_generated() {
    let suite = suite_features();

    let missing: Vec<&str> = REQUIRED
        .iter()
        .filter(|f| !suite.iter().any(|(_, found)| found.contains(f)))
        .map(|f| f.name())
        .collect();

    assert!(
        missing.is_empty(),
        "no generated pattern produces: {}\n\
         The end-to-end suite cannot measure a change to these constructs, so a \
         neutral benchmark result over them means nothing. Add them to a pattern \
         in src/bin/succinctly/yaml_generators.rs, or record them in OUT_OF_SCOPE \
         with a reason.",
        missing.join(", ")
    );
}

#[test]
fn out_of_scope_features_are_not_generated() {
    let suite = suite_features();

    for (feature, reason) in OUT_OF_SCOPE {
        let offenders: Vec<&str> = suite
            .iter()
            .filter(|(_, found)| found.contains(feature))
            .map(|(pattern, _)| pattern.as_str())
            .collect();

        assert!(
            offenders.is_empty(),
            "pattern(s) {} generate {}, which is out of scope: {reason}\n\
             If the underlying divergence is fixed, move this feature into \
             REQUIRED and give it a pattern.",
            offenders.join(", "),
            feature.name()
        );
    }
}

#[test]
fn feature_patterns_carry_their_headline_feature() {
    let suite = suite_features();

    for (pattern, expected) in HEADLINE {
        let found = suite
            .iter()
            .find(|(name, _)| name == pattern)
            .unwrap_or_else(|| panic!("pattern {pattern} is not registered with the CLI"));

        for feature in *expected {
            assert!(
                found.1.contains(feature),
                "pattern {pattern} no longer generates {} — the pattern exists to \
                 carry that construct end-to-end",
                feature.name()
            );
        }
    }
}

#[test]
fn generate_suite_covers_every_cli_pattern() {
    let dir =
        std::env::temp_dir().join(format!("succinctly-suite-coverage-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&dir);

    let output = Command::new(env!("CARGO_BIN_EXE_succinctly"))
        .args(["yaml", "generate-suite", "--output-dir"])
        .arg(&dir)
        .args(["--max-size", "1kb", "--clean", "--verify"])
        .output()
        .expect("failed to run `yaml generate-suite`");
    assert!(
        output.status.success(),
        "`yaml generate-suite` failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );

    let generated: BTreeSet<String> = std::fs::read_dir(&dir)
        .expect("suite directory missing")
        .map(|e| {
            e.expect("unreadable entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();

    let missing: Vec<String> = cli_pattern_names()
        .into_iter()
        .filter(|p| !generated.contains(p))
        .collect();

    let _ = std::fs::remove_dir_all(&dir);

    assert!(
        missing.is_empty(),
        "pattern(s) {} are accepted by `yaml generate` but produce no directory in \
         `yaml generate-suite` — register them in yaml_generators::ALL_PATTERNS",
        missing.join(", ")
    );
}
