fn run(input: &str, flags: &[&str], filter: &str) -> Result<(String, String, i32)> {
    let mut command = Command::new(env!("CARGO_BIN_EXE_succinctly"));
    command.arg("yq").args(flags).arg(filter);
    let mut child = command
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    std::io::Write::write_all(&mut child.stdin.take().expect("piped"), input.as_bytes())?;
    let output = child.wait_with_output()?;
    Ok((
        String::from_utf8_lossy(&output.stdout).into_owned(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
        output.status.code().unwrap_or(-1),
    ))
}

fn input(name: &str) -> &'static str {
    INPUTS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, text)| *text)
        .expect("a named input")
}

fn check(rows: &[(&str, &str, &[&str], &str)]) -> Result<()> {
    for (name, filter, flags, want) in rows {
        let (stdout, stderr, status) = run(input(name), flags, filter)?;
        assert_eq!(
            (stdout.as_str(), stderr.as_str(), status),
            (*want, "", 0),
            "{name} | yq {flags:?} {filter:?}"
        );
    }
    Ok(())
}

