#[test]
fn test_zero_padded_float_keeps_its_kind_across_a_write_6938() -> Result<()> {
    for (filter, expected) in PADDED_ROWS {
        let (out, code) = run_yq_stdin(filter, PADDED, &["-o=json", "-I0"])?;
        assert_eq!((out.as_str(), code), (*expected, 0), "{filter}");
    }
    Ok(())
}

#[test]
fn test_underscored_tagged_number_is_read_as_yq_does_6938() -> Result<()> {
    for (doc, filter, expected) in UNDERSCORE_ROWS {
        let (out, code) = run_yq_stdin(filter, doc, &["-o=json", "-I0"])?;
        assert_eq!((out.as_str(), code), (*expected, 0), "{doc:?} | {filter}");
    }
    Ok(())
}
