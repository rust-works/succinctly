//! #6938: two shapes around a zero-padded or underscored integer that differed from yq.
//!
//! 1. A zero-padded `08` or `09` is a float of a YAML document (#6866). After any write the document
//!    is rebuilt, and the value crossed the rebuild as a spelling that `tag`, `type` and the integer
//!    readers took for the integer 8: `.zz = 1 | .p | tag` was `!!int` where yq says `!!float` (the
//!    value itself was already `8.0`). An explicit `!!int 08` stays an integer through the rebuild.
//! 2. yq drops every `_` of a tag-forced number before it reads it, so `!!int 1_000` is 1000,
//!    `!!int 0_8` is 8 and `!!int 1__0` is 10, and `!!float 1_0.5` is 10.5 (a `_` that is not between
//!    two digits is refused for a float). It read these as the string.
//!
//! Every row is a live yq v4.53.3 capture (`-o=json -I0`), kept only where both agree. Left out: a
//! malformed form yq fails on in its JSON encoder (`!!int 0b1_0`, `!!int 1_0.5`), which this reads as
//! the string (the recorded divergence for `!!int abc`), and `tostring` of an underscored `!!float`,
//! which yq echoes as written and this prints as the number (`docs/compliance/yq/limitations.md`,
//! #6958).

