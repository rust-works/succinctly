#[test]
fn yq_refuses_a_line_between_the_dash_and_the_content_of_an_own_line_block_scalar_6550(
) -> Result<()> {
    for doc in REFUSED {
        let (stdout, status) = run_yq_stdin(".", doc, &["-o=json", "-I0"])?;
        assert_eq!((stdout.as_str(), status), ("", 1), "{doc:?}");
    }
    Ok(())
}

#[test]
fn yq_keeps_the_lines_that_belong_to_an_own_line_block_scalar_6550() -> Result<()> {
    for (doc, expected) in ACCEPTED {
        let (stdout, status) = run_yq_stdin(".", doc, &["-o=json", "-I0"])?;
        assert_eq!((stdout.trim_end(), status), (*expected, 0), "{doc:?}");
    }
    Ok(())
}
