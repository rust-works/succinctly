//! #7063: yq reads a run of backslashes before `(` by a rule that is not left-to-right pairing, and an
//! unclosed `\(` makes it keep the whole string as written. With `n` backslashes before `(`:
//!
//! - `n / 2` even (n = 1, 4, 5, 8, 9) starts an interpolation and keeps `n / 4` backslashes before the value;
//! - `n / 2` odd (n = 2, 3, 6, 7) keeps `n / 4 + 1` and the `(` as text;
//! - when any interpolation of the string is unclosed (no `)` before the string ends, counting nested
//!   parentheses), none is read, and every run before a `(` keeps `n / 2 + 1`, whether it would have started
//!   one or not; the text before and after stays.
//!
//! The same answer holds after a prefix, before a suffix and for each slot of a second one. Every row was
//! captured from yq v4.53.3 (`yq -n --from-file`, so no shell touches the backslashes). `succinctly yq`
//! agreed for one and two backslashes and read the rest left to right, and refused an unclosed `\(`.
//!
//! Not covered: yq's `level=WARN msg="unclosed interpolation string, skipping interpolation"` on stderr,
//! which is not printed here (recorded in the limitations page). A run before a character that is not `(`
//! is #7102's (`tests/yq_cli/i7102.rs`).

