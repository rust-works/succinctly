#[test]
fn a_backslash_run_before_a_paren_and_an_unclosed_interpolation_read_as_yq_does_7063() -> Result<()>
{
    let dir = TempDir::new()?;
    for &(program, want) in ROWS {
        let file = dir.path().join("p.yq");
        std::fs::write(&file, program)?;
        let output = Command::new(env!("CARGO_BIN_EXE_succinctly"))
            .args(["yq", "-n", "--from-file"])
            .arg(&file)
            .stdin(Stdio::null())
            .output()?;
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert_eq!(
            (
                String::from_utf8_lossy(&output.stdout).as_ref(),
                output.status.code()
            ),
            (want, Some(0)),
            "{program}: {stderr}"
        );
    }
    Ok(())
}

/// A string that never closes is the parser's own error, with or without a slot in it, and not an
/// unclosed interpolation: yq refuses all three as well.
#[test]
fn an_unterminated_string_is_refused_7063() -> Result<()> {
    for program in ["\"abc", "\"\\(1) abc", "\"abc\\\\"] {
        let output = Command::new(env!("CARGO_BIN_EXE_succinctly"))
            .args(["yq", "-n", program])
            .stdin(Stdio::null())
            .output()?;
        assert_eq!(output.status.code(), Some(1), "{program}");
        assert!(output.stdout.is_empty(), "{program}");
        assert!(!output.stderr.is_empty(), "{program}");
    }
    Ok(())
}
