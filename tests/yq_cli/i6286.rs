//! #6286: a line holding only a tab, after a plain scalar in block context, is refused when the tab sits
//! at a column no deeper than the block that owns the scalar (`found a tab character that violates
//! indentation`), and is an empty line otherwise; a document-root scalar has no block to violate. Every row
//! was captured from yq v4.53.3. The same line after a flow collection, a quoted scalar, a comment or an
//! empty value is refused at any column by yq, and is not changed here.

use anyhow::Result;

use crate::run_yq_stdin;

#[test]
fn a_tab_only_line_at_or_below_the_block_indent_after_a_plain_scalar_is_refused_6286() -> Result<()>
{
    for input in [
        "a: x\n  y\n\t\n  z\n",
        "a: x\n\t\n  z\n",
        "a: x\n# c\n\t\nb: 1\n",
        "x\n\n---\n\t\ny\n",
        "a: x\n\t\n",
        "a: x\n\t\t\n",
        "a: x\n\t \n",
        "a: x\n\t",
        "a: x\n\t\t",
        "a: x\n\t ",
        "a: x\n\t\nb: 1\n",
        "a: x\n\t\t\nb: 1\n",
        "a: x\n\t \nb: 1\n",
        "a:\n  b: x\n\t\n",
        "a:\n  b: x\n\t\t\n",
        "a:\n  b: x\n \t\n",
        "a:\n  b: x\n  \t\n",
        "a:\n  b: x\n \t \n",
        "a:\n  b: x\n\t \n",
        "a:\n  b: x\n  \t  \n",
        "a:\n  b: x\n\t\n  c: 1\n",
        "a:\n  b: x\n\t\t\n  c: 1\n",
        "a:\n  b: x\n \t\n  c: 1\n",
        "a:\n  b: x\n  \t\n  c: 1\n",
        "a:\n  b: x\n \t \n  c: 1\n",
        "a:\n  b: x\n\t \n  c: 1\n",
        "a:\n  b: x\n  \t  \n  c: 1\n",
        "- x\n\t\n",
        "- x\n\t\t\n",
        "- x\n\t \n",
        "- x\n\t\n- y\n",
        "- x\n\t\t\n- y\n",
        "- x\n\t \n- y\n",
        "a: x\n  y\n\t\n",
        "a: x\n  y\n\t\t\n",
        "a: x\n  y\n\t \n",
        "a: x\n\n\t\n",
        "a: x\n\n\t\t\n",
        "a: x\n\n\t \n",
        "a: x\n\t\n\t\n",
        "a: x\n\t\t\n\t\t\n",
        "a: x\n\t \n\t \n",
        "- a: x\n\t\n  b: 1\n",
        "- a: x\n\t\t\n  b: 1\n",
        "- a: x\n \t\n  b: 1\n",
        "- a: x\n  \t\n  b: 1\n",
        "- a: x\n \t \n  b: 1\n",
        "- a: x\n\t \n  b: 1\n",
        "- a: x\n  \t  \n  b: 1\n",
        "a:\n  b:\n    c: x\n\t\n",
        "a:\n  b:\n    c: x\n\t\t\n",
        "a:\n  b:\n    c: x\n \t\n",
        "a:\n  b:\n    c: x\n  \t\n",
        "a:\n  b:\n    c: x\n   \t\n",
        "a:\n  b:\n    c: x\n \t \n",
        "a:\n  b:\n    c: x\n\t \n",
        "a:\n  b:\n    c: x\n  \t  \n",
        "a:\n  - x\n\t\n  - y\n",
        "a:\n  - x\n\t\t\n  - y\n",
        "a:\n  - x\n \t\n  - y\n",
        "a:\n  - x\n  \t\n  - y\n",
        "a:\n  - x\n \t \n  - y\n",
        "a:\n  - x\n\t \n  - y\n",
        "a:\n  - x\n  \t  \n  - y\n",
    ] {
        let (out, code) = run_yq_stdin(".", input, &["-o=json", "-I=0"])?;
        assert_eq!(out.trim_end(), "", "{input:?}");
        assert_ne!(code, 0, "{input:?}");
    }
    Ok(())
}

