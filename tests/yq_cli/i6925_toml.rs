fn write_file(dir: &TempDir, name: &str, content: &[u8]) -> Result<std::path::PathBuf> {
    use std::io::Write;
    let path = dir.path().join(name);
    std::fs::File::create(&path)?.write_all(content)?;
    Ok(path)
}

/// yq takes TOML from a first file named `*.toml` (any case), and prints it as TOML under `-o auto`;
/// `.tml` is not an extension it knows, so that file is YAML; `-i` writes the table back as TOML.
#[test]
fn toml_by_extension_and_inplace_6925() -> Result<()> {
    let dir = TempDir::new()?;
    let a = write_file(&dir, "a.toml", b"a = 1\n[t]\nb = \"x\"\nc = [1, 2]\n")?;
    let upper = write_file(&dir, "B.TOML", b"x = 5\n")?;
    let tml = write_file(&dir, "c.tml", b"a = 1\n")?;
    let empty = write_file(&dir, "e.toml", b"")?;
    assert_eq!(
        run_yq_files(".", &[&a], &["-o", "json", "-I0"])?,
        (
            "{\"a\":1,\"t\":{\"b\":\"x\",\"c\":[1,2]}}\n".into(),
            String::new(),
            0
        )
    );
    assert_eq!(
        run_yq_files(".", &[&upper, &a], &[])?,
        (
            "x = 5\na = 1\n\n[t]\nb = \"x\"\nc = [1, 2]\n".into(),
            String::new(),
            0
        )
    );
    assert_eq!(
        run_yq_files(".", &[&tml], &["-o", "json", "-I0"])?,
        ("\"a = 1\"\n".into(), String::new(), 0)
    );
    assert_eq!(
        run_yq_files(".", &[&empty], &["-o", "json"])?,
        ("null\n".into(), String::new(), 0)
    );
    run_yq_files(".t.b = \"y\"", &[&a], &["-i"])?;
    assert_eq!(std::fs::read(&a)?, b"a = 1\n\n[t]\nb = \"y\"\nc = [1, 2]\n");
    Ok(())
}

/// A document nested more deeply than the reader will build is refused, where yq's stack grows as
/// far as memory allows (recorded in `limitations.md`).
#[test]
fn toml_input_refuses_nesting_past_the_bound_6925() -> Result<()> {
    let deep = format!("a = {}{}\n", "[".repeat(500), "]".repeat(500));
    let (out, err, status) = run_yq_stdin_with_stderr(".", &deep, &["-p", "toml"])?;
    assert_eq!(out, "");
    assert_eq!(
        error_line(&err),
        "Error: bad file '-': the document nests arrays, inline tables or dotted keys more than 400 levels deep"
    );
    assert_eq!(status, 1);
    let ok = format!("a = {}{}\n", "[".repeat(100), "]".repeat(100));
    let (out, _, status) =
        run_yq_stdin_with_stderr(". | .a | length", &ok, &["-p", "toml", "-o", "json"])?;
    assert_eq!(out, "1\n");
    assert_eq!(status, 0);
    let long_key = format!("{} = 1\n", vec!["k"; 500].join("."));
    let (out, err, status) = run_yq_stdin_with_stderr(".", &long_key, &["-p", "toml"])?;
    assert_eq!(out, "");
    assert!(
        error_line(&err).contains("more than 400 levels deep"),
        "{err}"
    );
    assert_eq!(status, 1);
    Ok(())
}
