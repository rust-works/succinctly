#[test]
fn test_a_timestamp_key_is_single_quoted_in_flow_context_on_a_write_5469() -> Result<()> {
    for (doc, want) in ROWS {
        let (stdout, stderr, code) = run_yq_stdin_with_stderr(".zz = 1", doc, &[])?;
        assert_eq!((stdout.as_str(), code), (*want, 0), "{doc:?}: {stderr:?}");
    }
    Ok(())
}
