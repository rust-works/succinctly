fn run(input: &str, args: &[&str]) -> Result<(String, String, i32)> {
    let mut child = Command::new(env!("CARGO_BIN_EXE_succinctly"))
        .arg("yq")
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    std::io::Write::write_all(&mut child.stdin.take().expect("piped"), input.as_bytes())?;
    let output = child.wait_with_output()?;
    Ok((
        String::from_utf8_lossy(&output.stdout).into_owned(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
        output.status.code().unwrap_or(-1),
    ))
}

fn input(name: &str) -> &'static str {
    INPUTS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, text)| *text)
        .expect("a named input")
}

#[test]
fn the_unwrap_flag_and_the_format_decide_how_a_scalar_prints_7093() -> Result<()> {
    for (name, args, want) in ROWS {
        let (stdout, stderr, status) = run(input(name), args)?;
        assert_eq!(
            (stdout.as_str(), stderr.as_str(), status),
            (*want, "", 0),
            "{name} | yq {args:?}"
        );
    }
    Ok(())
}

/// A value that is not a Go boolean is refused in cobra's words, with exit status 1.
#[test]
fn a_value_that_is_not_a_boolean_is_refused_as_yq_refuses_it_7093() -> Result<()> {
    for value in ["maybe", "falsE", "yes", "2", "TRUe"] {
        for flag in ["-r", "--unwrapScalar"] {
            let (stdout, stderr, status) = run("a: 1\n", &[&format!("{flag}={value}"), ".a"])?;
            assert_eq!((stdout.as_str(), status), ("", 1), "{flag}={value}");
            assert_eq!(
                stderr.lines().next(),
                Some(
                    format!(
                        "Error: invalid argument \"{value}\" for \"-r, --unwrapScalar\" flag: strconv.ParseBool: parsing \"{value}\": invalid syntax"
                    )
                    .as_str()
                ),
                "{flag}={value}"
            );
        }
    }
    Ok(())
}

/// Without `=`, the next word is the filter (a bool flag takes no separate value), as in yq.
#[test]
fn the_flag_takes_no_separate_value_7093() -> Result<()> {
    let (stdout, _, status) = run("a: 1\n", &["-r", "-o=json", ".a"])?;
    assert_eq!((stdout.as_str(), status), ("1\n", 0));
    Ok(())
}
