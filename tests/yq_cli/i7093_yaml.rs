fn run(input: &str, args: &[&str]) -> Result<(String, String, i32)> {
    let mut child = Command::new(env!("CARGO_BIN_EXE_succinctly"))
        .arg("yq")
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    std::io::Write::write_all(&mut child.stdin.take().expect("piped"), input.as_bytes())?;
    let output = child.wait_with_output()?;
    Ok((
        String::from_utf8_lossy(&output.stdout).into_owned(),
        String::from_utf8_lossy(&output.stderr).into_owned(),
        output.status.code().unwrap_or(-1),
    ))
}

fn input(name: &str) -> &'static str {
    INPUTS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, text)| *text)
        .expect("a named input")
}

#[test]
fn a_yaml_scalar_prints_as_a_node_under_false_and_kyaml_unwraps_under_true_7093() -> Result<()> {
    for (name, args, want) in ROWS {
        let (stdout, stderr, status) = run(input(name), args)?;
        assert_eq!(
            (stdout.as_str(), stderr.as_str(), status),
            (*want, "", 0),
            "{name} | yq {args:?}"
        );
    }
    Ok(())
}
