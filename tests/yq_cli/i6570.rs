#[test]
fn yq_refuses_a_line_below_an_own_line_scalar_in_an_explicit_key_sequence_6570() -> Result<()> {
    for doc in REFUSED {
        let (stdout, status) = run_yq_stdin(".", doc, &["-o=json", "-I0"])?;
        assert_eq!((stdout.as_str(), status), ("", 1), "{doc:?}");
    }
    Ok(())
}

#[test]
fn yq_keeps_the_documents_of_an_explicit_key_sequence_it_accepts_6570() -> Result<()> {
    for (doc, expected) in ACCEPTED {
        let (stdout, status) = run_yq_stdin(".", doc, &["-o=json", "-I0"])?;
        assert_eq!((stdout.trim_end(), status), (*expected, 0), "{doc:?}");
    }
    Ok(())
}

#[test]
fn yq_answers_the_explicit_key_sequences_that_changed_as_yq_does_6570() -> Result<()> {
    for (doc, expected) in CHANGED {
        let (stdout, status) = run_yq_stdin(".", doc, &["-o=json", "-I0"])?;
        match expected {
            Some(json) => assert_eq!((stdout.trim_end(), status), (*json, 0), "{doc:?}"),
            None => assert_eq!(status, 1, "{doc:?}"),
        }
    }
    Ok(())
}
