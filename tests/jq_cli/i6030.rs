//! #6030: `strftime` prints `%y` (and the year inside `%D` and `%x`) and `%C` of a negative year as the
//! pinned libc does (`_yconv`): `%y` is the absolute value of the year's remainder by 100 in two
//! digits, and `%C` is the quotient by 100, except that a negative year of fewer than three digits has
//! a century of 0 and prints `-0`. Every row is what `/usr/bin/jq` 1.7.1 printed for
//! `[YEAR,0,1,0,0,0,0,0] | strftime(FORMAT)` under `TZ=UTC`.

use std::process::Command;

use anyhow::Result;

use crate::{spawn_with_signal_retry, succinctly_bin};

/// `-nc PROGRAM` under `LC_ALL=C` (`%x` follows the process locale): stdout and the exit code.
fn run(program: &str) -> Result<(String, i32)> {
    let (output, code) = spawn_with_signal_retry(
        || {
            let mut command = Command::new(succinctly_bin());
            command
                .env("LC_ALL", "C")
                .env("TZ", "UTC")
                .args(["jq", "-nc", program]);
            command
        },
        None,
    )?;
    Ok((String::from_utf8(output.stdout)?, code))
}

