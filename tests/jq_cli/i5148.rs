//! #5148: a `reduce` with a field-navigation INIT and an UPDATE that hands the accumulator back.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// `reduce SRC as $i (.a; . as {b:$q} | .)`: INIT's navigation (`.a`, `.a.b`, `.a?`, `.a|.`, `first(.a)`, a comma of them) leaves jq's register on `.a` and the accumulator is that node,
// so UPDATE meets `.` on the register exactly as it does after `INIT .`, and an UPDATE that hands the accumulator back
// (a bind of `.`, a `try`, an `if`, `first`, a `label`) leaves it there. `keeps_accumulator` (#3953) was gated on
// `cannot_move_register(init)`, which a navigation fails, so the UPDATE was read as computing a value and the final
// emission was refused with the accumulator as the result (`[path(..)?]` lost the path). An INIT that computes
// (`.a|tostring`, `null`, `{}`) keeps its reading.

/// #5148: a navigation INIT (`.a`, `.a.b`, `.a?`, `.a|.`, `first(.a)`, `(.a,.b)`, `.["a"]`) around each bind shape and wrapper, under `path`, `[path(..)?]` and `|=`,
/// over documents where the pattern passes (a sample of the answering rows of the table), a source that moves the register
/// or yields nothing, and the INITs that compute. Every row captured from `/usr/bin/jq` 1.7.1 (stdout, exit code, message),
/// both routes.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
