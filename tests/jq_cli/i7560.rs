//! #7560: `split(re; flags)` and `splits(re; flags)` whose FLAGS argument yields nothing, on a
//! non-string input.
//!
//! jq 1.7.1 defines `splits($re; flags)` as `. as $s | [match($re; "g" + flags) | ...] | [0] + . +
//! [$s | length] | _nwise(2) | $s[.[0]:.[1]]`, so with no FLAGS value no `match` runs, nothing
//! checks the input's type, and the one piece is `$s[0:($s | length)]`: `null` for `null`, the
//! array itself for an array, `has no length` for a boolean and `Cannot index <type> with object`
//! for a number or an object. `succinctly jq` raised `cannot be matched, as it is not a string`.
//! jq 1.8.2 yields nothing for every input, strings included, because its rewrite of `splits`
//! (jqlang/jq#3260, a refactor that removed `_nwise`, not a fix) binds `$flags` as a value; 1.7.1
//! stays the reference. Every row is jq 1.7.1's answer, captured from `/usr/bin/jq`.

