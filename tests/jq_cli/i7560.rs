#[test]
fn test_split_with_no_flags_value_slices_a_non_string_input_whole_7560() -> Result<()> {
    for &(flags, input, filter, stdout, stderr, status) in ROWS {
        let mut args = vec!["-c"];
        args.extend_from_slice(flags);
        args.push(filter);
        let got = run_jq_full(&args, Some(input))?;
        assert_eq!(
            got,
            (stdout.to_string(), stderr.to_string(), status),
            "{flags:?} {filter} over {input:?}"
        );
    }
    Ok(())
}
