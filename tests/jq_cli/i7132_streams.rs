/// `input_line_number` over a bound value is the reader's last line, as jq reads it (`/usr/bin/jq`
/// 1.7.1: `[2,2]` after a two-line document, `[5,5]` after a second of three lines), in a loop and in
/// a fold.
#[test]
fn input_line_number_over_a_bound_value_is_the_readers_line_7132() -> Result<()> {
    let input = "[1,\n2]\n[3,\n4,\n5]\n";
    let (out, err, code) = run_jq_full(
        &["-c", "[.[]] as $a | [range(2) | $a | input_line_number]"],
        Some(input),
    )?;
    assert_eq!(
        (out.as_str(), err.as_str(), code),
        ("[2,2]\n[5,5]\n", "", 0)
    );
    let (out, err, code) = run_jq_full(
        &[
            "-c",
            "[.[]] as $a | reduce range(2) as $i (0; $a | input_line_number)",
        ],
        Some(input),
    )?;
    assert_eq!((out.as_str(), err.as_str(), code), ("2\n5\n", "", 0));
    Ok(())
}

/// The cost is the shape of the stages and not a timing: seven stages, each its own `range | $a | STAGE`
/// loop or fold, over a 50,000-element array the filter computed, 200 calls each. Through the bridge
/// each call wrote the array out and indexed it again: 151 s for this program on the unoptimized binary
/// before, a fraction of a second after, so the bound is far from both.
#[test]
fn streams_over_a_bound_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let start = Instant::now();
    let (out, code) = run_jq_null(
        "[range(50000)] as $a | ([range(200) | $a | first, last] + [range(200) | $a | first(.[])] + [range(200) | $a | limit(2; .[])] + [range(200) | $a | isempty(.[])] + [range(200) | $a | $__loc__] + [range(200) | $a | input_line_number]) | length, reduce range(200) as $i (0; . + ($a | nth(1; .[])))",
        &["-c"],
    )?;
    let took = start.elapsed();
    assert_eq!((out.as_str(), code), ("1600\n200\n", 0));
    assert!(took < Duration::from_secs(15), "{took:?}");
    Ok(())
}

