#[test]
fn a_chain_a_bind_or_an_if_over_a_bound_value_answers_as_jq_does_7132() -> Result<()> {
    for &(program, stdout, stderr, code) in NULL_INPUT_ROWS {
        let (out, err, status) = run_jq_full(&["-c", "-n", program], None)?;
        assert_eq!(
            (out.as_str(), err.as_str(), status),
            (stdout, stderr, code),
            "{program}"
        );
    }
    for &(input, program, stdout, stderr, code) in DOCUMENT_ROWS {
        let (out, err, status) = run_jq_full(&["-c", program], Some(input))?;
        assert_eq!(
            (out.as_str(), err.as_str(), status),
            (stdout, stderr, code),
            "{program} over {input}"
        );
    }
    Ok(())
}

/// The cost is the shape of the stages and not a timing: four stages over a 50,000-element array, 200
/// calls each (this runs the unoptimized binary), took seconds through the bridge in an optimized build
/// and well under a second answered from the value, so the bound is far from both.
#[test]
fn chains_binds_and_ifs_over_a_bound_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let start = Instant::now();
    let (out, code) = run_jq_null(
        "[range(50000)] | . as $a | [range(200) | ($a | length | tostring), ($a | length as $n | $n + 1), ($a | if length > 5 then 1 else 0 end), ($a | has(0) | not)] | length",
        &["-c"],
    )?;
    let took = start.elapsed();
    assert_eq!((out.trim(), code), ("800", 0));
    assert!(took < Duration::from_secs(15), "{took:?}");
    Ok(())
}
