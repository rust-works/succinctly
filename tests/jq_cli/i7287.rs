#[test]
fn test_number_spellings_decode_as_jq_7287() -> Result<()> {
    for (filter, stdout) in ROWS {
        let (out, err, code) = run_jq_full(&["-c", filter], Some(DOCUMENT))?;
        assert_eq!(
            (out.as_str(), err.as_str(), code),
            (*stdout, "", 0),
            "{filter}"
        );
    }
    Ok(())
}
