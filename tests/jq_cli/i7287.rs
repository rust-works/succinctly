//! #7287: a document number's integer read stops at its first non-digit, and its text is
//! borrowed without a second UTF-8 pass. Neither changes an answer: each row is
//! `(filter, stdout)` as jq 1.7.1 (`/usr/bin/jq`) answers over one array of spellings (signs,
//! `-0`, a leading zero, fractions, exponents, the `i64` bounds and one past each, past `u64`,
//! 21 digits, `1e1000`), read from stdin, so every spelling takes the integer read and the
//! float fallback the way it did.

