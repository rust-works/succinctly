/// A repeated key, compared after decoding: first position, last value, one event.
const COLLAPSED: &[Row] = &[
    (
        &["--stream", "-c", "-s", "."],
        r#"{"a":1,"a":2}"#,
        "[[[\"a\"],2]]\n[[\"a\"]]",
        0,
    ),
    (
        &["--stream", "-c", "-s", "."],
        r#"{"a":1,"b":2,"a":3}"#,
        "[[[\"a\"],3],[[\"b\"],2]]\n[[\"b\"]]",
        0,
    ),
    (
        &["--stream", "-n", "-c", "[inputs]"],
        "[1] {\"x\":{\"a\":[1],\"a\":{}}}\n",
        r#"[[[0],1],[[0]],[["x","a"],{}],[["x","a"]],[["x"]]]"#,
        0,
    ),
    (
        &["--stream", "-n", "-c", "[inputs]"],
        r#"{"a":1,"a":2}"#,
        r#"[[["a"],2],[["a"]]]"#,
        0,
    ),
];

#[test]
fn test_stream_events_built_from_the_index_match_jq_5618() -> Result<()> {
    for (args, stdin, expected, code) in ROWS.iter().chain(COLLAPSED) {
        let (stdout, stderr, status) = run_jq_full(args, Some(stdin))?;
        assert_eq!(
            (stdout.trim_end(), status),
            (*expected, *code),
            "{args:?} on {stdin:?}: stderr {stderr}"
        );
    }
    Ok(())
}
