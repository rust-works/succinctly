/// White space the windowed rows were captured with ahead of the document: jq's columns count it.
const CAPTURED_PAD: usize = 40_000;

/// `text` with every `line 1, column N` moved by `by` columns (the windowed rows' padding).
fn shift_columns(text: &str, by: isize) -> String {
    const AT: &str = "line 1, column ";
    let mut out = String::new();
    let mut rest = text;
    while let Some(found) = rest.find(AT) {
        let (head, tail) = rest.split_at(found + AT.len());
        out.push_str(head);
        let digits = tail.bytes().take_while(u8::is_ascii_digit).count();
        let column: isize = tail[..digits].parse().unwrap();
        out.push_str(&(column + by).to_string());
        rest = &tail[digits..];
    }
    out.push_str(rest);
    out
}

