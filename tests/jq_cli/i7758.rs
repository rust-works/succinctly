#[test]
fn an_escape_jq_refuses_is_its_catchable_parse_error_on_the_input_routes_7758() -> Result<()> {
    let mut failures = Vec::new();
    for &(shape, run, delivery, stdout, stderr, code) in JQ_ROWS {
        let (_, text) = SHAPES.iter().find(|(name, _)| *name == shape).unwrap();
        let doc = format!("{text}\n2\n");
        let windowed = run.starts_with("win40k");
        let pad = if windowed { small_window::MIN_BYTES } else { 0 };
        let dir = tempfile::tempdir()?;
        std::fs::write(
            dir.path().join("f.json"),
            format!("{}{doc}", " ".repeat(pad)),
        )?;
        let mut args: Vec<&str> = args_of(run).to_vec();
        if delivery == "file" {
            args.push("f.json");
        }
        let stdin = (delivery == "pipe").then_some(doc.as_bytes());
        let (output, got_code) = spawn_with_signal_retry(
            || {
                let mut command = std::process::Command::new(succinctly_bin());
                command
                    .arg("jq")
                    .args(&args)
                    .current_dir(dir.path())
                    .env_remove(small_window::ENV);
                if windowed {
                    small_window::apply(&mut command);
                }
                command
            },
            stdin,
        )?;
        let by = if windowed {
            pad as isize - CAPTURED_PAD as isize
        } else {
            0
        };
        let (want_out, want_err) = (shift_columns(stdout, by), shift_columns(stderr, by));
        let got_out = String::from_utf8_lossy(&output.stdout);
        let got_err = String::from_utf8_lossy(&output.stderr);
        if (got_out.as_ref(), got_err.as_ref(), got_code)
            != (want_out.as_str(), want_err.as_str(), code)
        {
            failures.push(format!(
                "{shape} {run} {delivery}: ({got_out:?}, {got_err:?}, {got_code}) \
                 where jq answers ({want_out:?}, {want_err:?}, {code})"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} rows:\n{}",
        failures.len(),
        JQ_ROWS.len(),
        failures.join("\n")
    );
    Ok(())
}

/// The issue's rows, spelled out.
#[test]
fn a_lone_high_surrogate_is_caught_and_the_reads_go_on_7758() -> Result<()> {
    let run = |program: &str, input: &str| -> Result<(String, String, i32)> {
        let (output, code) = spawn_with_signal_retry(
            || {
                let mut command = std::process::Command::new(succinctly_bin());
                command.args(["jq", "-c", "-n", program]);
                command
            },
            Some(input.as_bytes()),
        )?;
        Ok((
            String::from_utf8_lossy(&output.stdout).into_owned(),
            String::from_utf8_lossy(&output.stderr).into_owned(),
            code,
        ))
    };
    let caught = "\"Invalid \\\\uXXXX\\\\uXXXX surrogate pair escape at line 1, column 8\"\n2\n";
    assert_eq!(
        run("(try input catch .), input", "\"\\ud83d\"\n2\n")?,
        (caught.to_string(), String::new(), 0)
    );
    assert_eq!(
        run("[inputs?]", "\"\\ud83d\"\n2\n")?,
        ("[]\n".to_string(), String::new(), 0)
    );
    assert_eq!(
        run("[inputs?]", "{\"\\ud800\":1}\n2\n")?,
        ("[]\n".to_string(), String::new(), 0)
    );
    assert_eq!(
        run("try input catch .", "{\"\\x\":1}\n2\n")?,
        (
            "\"Invalid escape at line 1, column 5\"\n".to_string(),
            String::new(),
            0
        )
    );
    Ok(())
}
