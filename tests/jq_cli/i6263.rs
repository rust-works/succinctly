//! #6263: jq's `\w` (and `\W`, `\p{Word}`) is one operation in Oniguruma, but the translation writes it
//! as a bracketed class, and the count of a lazy counted repeat's body took any bracketed class under
//! case folding for a long body: under the `n` flag the repeat got the counted-loop rewrite where jq
//! writes plain copies, so `"ca" | [match("(?i)(?:a?|\\w){2,}?"; "gn") | .string]` was `["ca"]` and jq's
//! answer is `["c","a"]`. Every row was captured from jq 1.7.1 (`/usr/bin/jq -n -r`).

use anyhow::Result;

use crate::run_jq_full;

#[test]
fn test_a_word_class_under_case_folding_is_one_operation_in_a_counted_repeat_6263() -> Result<()> {
    for (pattern, flags, text, expected) in [
        (r"(?i)(?:a?|\w){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\w){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\w){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\W){2,}?", "gn", "ca-", r#"["a","-"]"#),
        (r"(?i)(?:a?|\W){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\W){2,}?", "gn", "a_b", r#"["a"]"#),
        (r"(?i)(?:a?|\W){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\p{Word}){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\p{Word}){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\p{Word}){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\p{Word}){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:\w|a?){2,}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:\w|a?){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:\w|a?){2,}?", "gn", "a_b", r#"["a_","b"]"#),
        (r"(?i)(?:\w|a?){2,}?", "g", "ca-", r#"["ca","",""]"#),
        (r"(?i)(?:b?|\w){3,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:b?|\w){3,}?", "gn", "aaa", r#"["a","a","a"]"#),
        (r"(?i)(?:b?|\w){3,}?", "gn", "a_b", r#"["a","_b"]"#),
        (r"(?i)(?:b?|\w){3,}?", "g", "ca-", r#"["","","",""]"#),
        (r"(?i)(?:a?|\w\w){2,}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\w\w){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\w\w){2,}?", "gn", "a_b", r#"["a","_b"]"#),
        (r"(?i)(?:a?|\w\w){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w){1,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\w){1,}?", "gn", "aaa", r#"["a","a","a"]"#),
        (r"(?i)(?:a?|\w){1,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){1,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w){0,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\w){0,}?", "gn", "aaa", r#"["a","a","a"]"#),
        (r"(?i)(?:a?|\w){0,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){0,}?", "g", "ca-", r#"["","","",""]"#),
        (r"(?i)(?:a?|\w)+?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\w)+?", "gn", "aaa", r#"["a","a","a"]"#),
        (r"(?i)(?:a?|\w)+?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w)+?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w)*?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i)(?:a?|\w)*?", "gn", "aaa", r#"["a","a","a"]"#),
        (r"(?i)(?:a?|\w)*?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w)*?", "g", "ca-", r#"["","","",""]"#),
        (r"(?i)(?:a?|\w){2,3}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\w){2,3}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\w){2,3}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){2,3}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w){2,3}", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\w){2,3}", "gn", "aaa", r#"["aaa"]"#),
        (r"(?i)(?:a?|\w){2,3}", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){2,3}", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w){2,}", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\w){2,}", "gn", "aaa", r#"["aaa"]"#),
        (r"(?i)(?:a?|\w){2,}", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w){2,}", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|[\w-]){2,}?", "gn", "ca-", r#"["ca","-"]"#),
        (r"(?i)(?:a?|[\w-]){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|[\w-]){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|[\w-]){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|[^\w]){2,}?", "gn", "ca-", r#"["a","-"]"#),
        (r"(?i)(?:a?|[^\w]){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|[^\w]){2,}?", "gn", "a_b", r#"["a"]"#),
        (r"(?i)(?:a?|[^\w]){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\d|\w){2,}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\d|\w){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\d|\w){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\d|\w){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|ss|\w){2,}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|ss|\w){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|ss|\w){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|ss|\w){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?i)(?:a?|\w|ß){2,}?", "gn", "ca-", r#"["ca"]"#),
        (r"(?i)(?:a?|\w|ß){2,}?", "gn", "aaa", r#"["aa","a"]"#),
        (r"(?i)(?:a?|\w|ß){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?i)(?:a?|\w|ß){2,}?", "g", "ca-", r#"["","a","",""]"#),
        (r"(?:a?|(?i-s:\w)){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?:a?|(?i-s:\w)){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?:a?|(?s:\w)){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?:a?|(?s:\w)){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?:a?|(?i)\w){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?:a?|(?i)\w){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
        (r"(?:a?|(?i:\W)){2,}?", "gn", "ca-", r#"["a","-"]"#),
        (r"(?:a?|(?i:\W)){2,}?", "gn", "a_b", r#"["a"]"#),
        (r"(?:a?|(?i-s:\p{Word})){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (
            r"(?:a?|(?i-s:\p{Word})){2,}?",
            "gn",
            "a_b",
            r#"["a","_","b"]"#,
        ),
        (r"(?i:(?:a?|\w)){2,}?", "gn", "ca-", r#"["c","a"]"#),
        (r"(?i:(?:a?|\w)){2,}?", "gn", "a_b", r#"["a","_","b"]"#),
    ] {
        let (stdout, stderr, status) = run_jq_full(
            &[
                "-n",
                "-r",
                "--arg",
                "p",
                pattern,
                "--arg",
                "f",
                flags,
                "--arg",
                "t",
                text,
                r"$t | [match($p; $f) | .string] | tojson",
            ],
            None,
        )?;
        assert_eq!(
            (stdout.trim_end(), status),
            (expected, 0),
            "{pattern} {flags} {text}: {stderr}"
        );
    }
    Ok(())
}
