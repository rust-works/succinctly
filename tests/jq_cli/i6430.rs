//! #6430: a loop with capture groups in a pattern that uses a group name twice answers as Oniguruma's does.
//! `regex-syntax` refuses a repeated name, so both loop rewrites used to leave such a pattern as written
//! and the loop kept the crate's last iteration: `"ba" | [match("(?:(?<n>a)|(?<n>a)|())*";"g")] | .[1].captures`
//! was `["a",null,null]` where jq 1.7.1 answers `["a",null,""]`. Every row was captured from jq 1.7.1 (`jq -nc`).

use anyhow::Result;

use crate::run_jq_full;

