/// The renamed copies the rewrite parses are not seen: each group reports the name it was written with.
#[test]
fn a_repeated_group_name_is_reported_as_written_6430() -> Result<()> {
    for (pattern, input, expected) in [
        (
            "(?:(?<n>a)|(?<n>a)|())*",
            "ba",
            "[[\"n\",\"n\",null],[\"n\",\"n\",null],[\"n\",\"n\",null]]",
        ),
        (
            "(?:(?<n>a)|(?<n>a)|())*",
            "aab",
            "[[\"n\",\"n\",null],[\"n\",\"n\",null],[\"n\",\"n\",null]]",
        ),
        (
            "(?:(?<n>a)|(?<n>a)|())+",
            "ba",
            "[[\"n\",\"n\",null],[\"n\",\"n\",null],[\"n\",\"n\",null]]",
        ),
        (
            "(?:(?<n>a)|(?<n>a)|())+",
            "aab",
            "[[\"n\",\"n\",null],[\"n\",\"n\",null],[\"n\",\"n\",null]]",
        ),
        (
            "(?:(?<n>a)|(?<n>a)|(?<z>))*",
            "ba",
            "[[\"n\",\"n\",\"z\"],[\"n\",\"n\",\"z\"],[\"n\",\"n\",\"z\"]]",
        ),
        (
            "(?:(?<n>a)|(?<n>a)|(?<z>))*",
            "aab",
            "[[\"n\",\"n\",\"z\"],[\"n\",\"n\",\"z\"],[\"n\",\"n\",\"z\"]]",
        ),
        (
            "(?:(?<n>b*)|(?<n>a))+",
            "ba",
            "[[\"n\",\"n\"],[\"n\",\"n\"],[\"n\",\"n\"]]",
        ),
        (
            "(?:(?<n>b*)|(?<n>a))+",
            "aab",
            "[[\"n\",\"n\"],[\"n\",\"n\"],[\"n\",\"n\"],[\"n\",\"n\"]]",
        ),
        (
            "((?<n>a)|(?<n>b)|)*c?",
            "ba",
            "[[null,\"n\",\"n\"],[null,\"n\",\"n\"]]",
        ),
        (
            "((?<n>a)|(?<n>b)|)*c?",
            "aab",
            "[[null,\"n\",\"n\"],[null,\"n\",\"n\"]]",
        ),
    ] {
        let (stdout, _, status) = run_jq_full(
            &[
                "-nc",
                "--arg",
                "s",
                input,
                "--arg",
                "p",
                pattern,
                r#"[$s | match($p; "g") | .captures | map(.name)]"#,
            ],
            None,
        )?;
        assert_eq!(
            (stdout.trim_end(), status),
            (expected, 0),
            "{pattern:?} on {input:?}"
        );
    }
    Ok(())
}
