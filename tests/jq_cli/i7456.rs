#[test]
fn format_string_is_an_import_path_7456() -> Result<()> {
    for &(program, want) in IMPORTS {
        let (stdout, stderr, code) = run_jq_with_module(r#"def hi: "hi";"#, &["-nc", program])?;
        assert_eq!((stdout.as_str(), code), (want, 0), "`{program}`: {stderr}");
    }
    // An interpolated path is refused with or without a format (jq: `Import path must be constant`).
    for program in [
        r#"import @text "m\(1)" as m; 1"#,
        r#"include @text "m\(1)"; 1"#,
    ] {
        let (stdout, stderr, code) = run_jq_with_module(r#"def hi: "hi";"#, &["-nc", program])?;
        assert_eq!((stdout.as_str(), code), ("", 3), "`{program}`: {stderr}");
    }
    Ok(())
}

/// yq's lexer rejects a format followed by a string (`bad expression`, v4.53.3), and `.@base64`
/// alone is the key `@base64` there.
#[test]
fn yq_mode_keeps_refusing_a_format_string_after_a_dot_7456() -> Result<()> {
    let input = r#"{"x": 2, "a": {"b": 3}, "@base64": 4, "c": 7}"#;
    for (filter, want) in [
        (r#".@base64 "x""#, None),
        (r#". @base64 "x""#, None),
        (r#".a.@text "b""#, None),
        (r#".@base64 "x" = 9"#, None),
        (r#"{@base64 "c": 1}"#, None),
        (r#"del(.@text "x")"#, None),
        (".@base64", Some("4\n")),
    ] {
        let (output, code) = spawn_with_signal_retry(
            || {
                let mut command = std::process::Command::new(succinctly_bin());
                command.args(["yq", "-o=json", "-I=0", filter]);
                command
            },
            Some(input.as_bytes()),
        )?;
        let stdout = String::from_utf8(output.stdout)?;
        match want {
            Some(want) => assert_eq!(stdout, want, "`{filter}`"),
            None => assert_eq!((stdout.as_str(), code), ("", 1), "`{filter}`"),
        }
    }
    Ok(())
}
