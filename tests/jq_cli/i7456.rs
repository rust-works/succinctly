//! #7456: a format-prefixed string is jq's `String` production wherever a plain one is, so it is a
//! field step after `.` (`.@base64 "x"`, `. @json "k"`, `.a.@text "b"`), an object-pattern key
//! (`. as {@base64 "c": $c}`) and an `import`/`include` path, as well as the standalone string and
//! the object-construction key (#3316, #5298). `succinctly jq` refused the first three with
//! `expected identifier, found '@'` / `expected '"', found '@'`.
//!
//! jq 1.7.1's `parser.y` takes `String: FORMAT QQSTRING_START QQString QQSTRING_END | QQSTRING_START
//! ...` in `Term '.' String ['?']`, `'.' String ['?']`, `Term: String`, `ObjPat: String ':'
//! Pattern`, `MkDictPair: String ':' ExpD | String` and `ImportFrom: String`. The format runs on
//! each interpolation only, so `.@base64 "x"` is `.["x"]` and `.@base64 "\(1)"` is `.["MQ=="]`.
//! jq 1.8.2 has the same productions and agrees on every row below.
//!
//! `MATRIX` is generated: every position above (plus the path-mode ones: `path`, `paths`, `=`,
//! `|=`, `del`) x 9 of jq's formats and one unknown name x a plain and an interpolated string, with
//! the input holding the key jq computes. The outputs are jq 1.7.1's, captured live by the script
//! that generated the table, which also checked jq 1.8.2 against each. `@yaml`, `@props`, `@dsv` and
//! `@urid` are left out: succinctly disagrees with jq 1.7.1 on them in the standalone form too.
//! `succinctly yq` keeps refusing a format followed by a string, as yq's lexer does (#3316).

