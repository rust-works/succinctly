/// Each row from stdin (the document evaluator) and as a `-n` literal piped into the filter (the
/// owned one); the second's error text names no input, so only its stdout and exit are pinned.
fn check_rows(rows: &[Row], format: &str) -> Result<()> {
    let mut seen = 0;
    for &(id, filter, input, stdout, stderr, code) in rows {
        if id.split('/').next() != Some(format) {
            continue;
        }
        seen += 1;
        let got = run_jq_full(&["-c", filter], Some(input))?;
        assert_eq!(
            (got.0.as_str(), got.1.as_str(), got.2),
            (stdout, stderr, code),
            "{id}: stdin `{filter}`"
        );
        let literal = format!("{input} | {filter}");
        let got = run_jq_full(&["-nc", &literal], None)?;
        assert_eq!(
            (got.0.as_str(), got.2),
            (stdout, code),
            "{id}: -n `{literal}`: {}",
            got.1
        );
    }
    assert_eq!(seen, 40, "{format}: rows");
    Ok(())
}

macro_rules! format_tests {
    ($($name:ident => $format:literal,)*) => {
        $(
            #[test]
            fn $name() -> Result<()> {
                check_rows(MATRIX, $format)
            }
        )*
    };
}

