/// #5023: shapes jq refuses never get an answer: a no-op pipe outside a `foreach` UPDATE keeps the refusal it had
/// (the fix is the UPDATE's, not the shared resolver's: handing the seed on there answered
/// the first row, `del` writing `null`, and the second, a pipe off the root). Every row captured from `/usr/bin/jq` 1.7.1.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
fn test_5023_shapes_jq_refuses_are_not_answered() -> Result<()> {
    let rows: &[(&str, &str)] = &[
        (
            r"[null]",
            r"del(reduce (foreach (1,2) as $j (.; . as [$a,$b] | .; empty)) as $i (. as [$q] ?// $z | (.|.)//1; .))",
        ),
        (
            r#"{"a":{"b":1}}"#,
            r"path(. as $x | reduce .[]? as $i (.; reduce (select(.a) | . as {a:$a} | .) as $y (.; .)))",
        ),
    ];
    for (input, filter) in rows {
        let (stdout, stderr, code) = run_jq_full(&["-c", filter], Some(input))?;
        assert_eq!(
            code, 5,
            "{filter} on {input}: jq refuses it, binary stdout {stdout:?}"
        );
        assert!(
            stdout.is_empty(),
            "{filter} on {input}: answered {stdout:?} where jq refuses"
        );
        assert!(
            stderr.contains("Invalid path expression"),
            "{filter} on {input}: refused for another reason: {stderr:?}"
        );
    }
    Ok(())
}
