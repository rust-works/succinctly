//! #5023: a `foreach` UPDATE that is a pipe of no-ops (`.|.`) over an untracked state hands it on as a bare `.` does.

use anyhow::Result;

use crate::{assert_path_rows_both_routes_3749, run_jq_full};

// The resolver's pipe route raised #530's "with result" refusal on the untracked state a no-op chain flattened to
// (`push_path_components` drops every `Identity`). That is the terminal's check of a value that is not the register; a
// fold's UPDATE stores its output unchecked, so `foreach (.) as $i (null; (.|.); $x)` was refused (and `[path(..)?]`
// dropped the path) where jq answers from the EXTRACT, as it does for a lone `.`. `.|.` is `.` in jq wherever it
// stands, so the fold now reads every no-op pipe in its UPDATE as the `.` it is.

/// #5023: `(.|.)`, `(.|.|.)`, a comma sibling of one, `try`/`?` around one, `//` and `first` with one, an `if`, `limit`,
/// a bind, a `label`, a `catch` handler and a pipe's last stage around one as the UPDATE, over an INIT that is `null`, a number and `[]`,
/// under a `$x` or `$i` EXTRACT; `[path(..)?]`, `try path(..) catch`, `try del(..) catch`. The last block holds the
/// terminal's own refusals, which stay, and the no-op pipes outside a UPDATE. Every row captured from `/usr/bin/jq` 1.7.1 (stdout, first stderr line up to the container, exit
/// code), both routes.
#[test]
