/// The cost is the shape of the stages and not a timing: five stages, each its own `range | $a | STAGE`
/// pipe (a comma of operands is evaluated another way), over a 100,000-element input array, 100 calls
/// each (this runs the unoptimized binary), took 2 s through the bridge in an optimized build and well
/// under a second answered from the value, so the bound is far from both.
#[test]
fn stages_over_the_input_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let input = format!(
        "[{}]",
        (0..100_000)
            .map(|i| i.to_string())
            .collect::<Vec<_>>()
            .join(",")
    );
    let start = Instant::now();
    let (out, err, code) = run_jq_full(
        &[
            "-c",
            ". as $a | ([range(100) | $a | has(5)] + [range(100) | $a | length | tostring] + [range(100) | $a | length as $n | $n + 1] + [range(100) | $a | if length > 5 then 1 else 0 end] + [range(100) | $a | last]) | length",
        ],
        Some(&input),
    )?;
    let took = start.elapsed();
    assert_eq!((out.trim(), err.as_str(), code), ("500", "", 0));
    assert!(took < Duration::from_secs(20), "{took:?}");
    Ok(())
}
