/// The cost is the shape of the stages and not a timing: six stages, each its own `range | $a | STAGE`
/// pipe, over a 50,000-element array the filter computed, 200 calls each. Through the bridge each call
/// wrote the array out and indexed it again; this runs the unoptimized binary, so the bound is far from
/// both.
#[test]
fn slices_of_a_bound_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let start = Instant::now();
    let (out, code) = run_jq_null(
        "[range(50000)] as $a | ([range(200) | $a | .[5:] | length] + [range(200) as $i | $a | .[$i:] | length] + [range(200) | $a | .[5:][0]] + [range(200) | $a | .[5:]? | length] + [range(200) | $a | .[-3:] | first]) | length, reduce range(200) as $i (0; . + ($a | nth(5)))",
        &["-c"],
    )?;
    let took = start.elapsed();
    assert_eq!((out.as_str(), code), ("1000\n1000\n", 0));
    assert!(took < Duration::from_secs(15), "{took:?}");
    Ok(())
}
