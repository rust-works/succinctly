/// #4933: the destructure of `.` or of an outer `$x` that a fold nested in a `reduce` UPDATE (whose source
/// moved jq's register onto an element) runs raises `Invalid path expression near attempt to access element
/// "a" of <container>` at the step in jq. The binary refused the same rows, with the same stdout and exit
/// code, but worded them as the end of the path (`with result <accumulator>`) whenever the destructure was
/// not the first stage of the source: behind a `select(..)` that passes, inside `[ .. ]`, behind a `//` whose
