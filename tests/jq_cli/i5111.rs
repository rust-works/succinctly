//! #5111: the body-`.` hand-on of a bind of a `$x` marker in a three-argument `foreach` UPDATE.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// `. as $x | foreach SRC as $i (INIT; 1 | ($x as {a:$q} | .); $i)`: jq stores UPDATE's output as the next state without a
// path check, so the `.` the bind's body ends on (`1`, the pipe's computed input) is left unchecked and EXTRACT's emission is
// judged at the register the bind moved to. `resolve_reduce` has had that reading for a `reduce` UPDATE since #4901
// (`fold_body::state_handed_on`); a `foreach` UPDATE was refused at the end of the path with `with result 1`, so `path`,
// `del` and `|=` failed where jq answers. A two-argument `foreach` emits UPDATE's output, which is checked, so it keeps the
// refusal, as does an EXTRACT that is the checked `.`.

/// #5111: the issue's row in `path`, `del`, `|=` and `[path(..)?]`, the controls that keep refusing as jq does (EXTRACT `.`,
/// no EXTRACT, an EXTRACT that is the checked `.` through `(..)`, `.|.`, `first(.)`, `select(true)` or `label`, a register that is not `null`), and rows of a differential grid (document x bind site x head stage x bind x
/// source x INIT x EXTRACT x context) that `main` refused or answered wrongly. Every row captured from `/usr/bin/jq` 1.7.1
/// (stdout, exit code, message), both routes.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
