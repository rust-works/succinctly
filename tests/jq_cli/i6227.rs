//! #6227: `\p{Word}` (and `\P{Word}`, `\p{^Word}`) was the `regex` crate's property, which lacks the
//! six Latin-1 `No` characters (U+00B2, U+00B3, U+00B9, U+00BC-U+00BE) that jq's word class has
//! outside a class and has the two joiners (U+200C, U+200D) that jq's does not. It is now the class
//! `\w` is (#5373): inside `[...]` jq's has neither the six nor the joiners. Every row was captured
//! from jq 1.7.1 (`/usr/bin/jq -n`). `\b` and `\B` still use the crate's definition; see
//! `docs/compliance/jq/limitations.md`.

use anyhow::Result;

use crate::run_jq_full;

/// (subject, jq's `[offset, length]` list).
type Answer = (&'static str, &'static str);

/// `$s | [match($p; "g") | [.offset, .length]]`, compact.
fn matches(subject: &str, pattern: &str) -> Result<String> {
    let (stdout, stderr, code) = run_jq_full(
        &[
            "-nc",
            "--arg",
            "p",
            pattern,
            "--arg",
            "s",
            subject,
            r#"$s | [match($p; "g") | [.offset, .length]]"#,
        ],
        None,
    )?;
    assert_eq!(code, 0, "{pattern}: stderr={stderr:?}");
    Ok(stdout.trim_end().to_string())
}

