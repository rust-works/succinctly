#[test]
fn a_stage_over_a_bound_value_answers_as_jq_does_7132() -> Result<()> {
    for &(program, stdout, stderr, code) in NULL_INPUT_ROWS {
        let (out, err, status) = run_jq_full(&["-c", "-n", program], None)?;
        assert_eq!(
            (out.as_str(), err.as_str(), status),
            (stdout, stderr, code),
            "{program}"
        );
    }
    for &(input, program, stdout, stderr, code) in DOCUMENT_ROWS {
        let (out, err, status) = run_jq_full(&["-c", program], Some(input))?;
        assert_eq!(
            (out.as_str(), err.as_str(), status),
            (stdout, stderr, code),
            "{program} over {input}"
        );
    }
    Ok(())
}

/// The cost is the shape of the stages and not a timing: five stages (each its own pipe: a comma of
/// them is one stage no door takes) over a 50,000-element array, 200 calls each, took 2 s through the
/// bridge in an optimized build and well under a second answered from the value. This runs the
/// unoptimized binary, so the bound is far from both.
#[test]
fn stages_over_a_bound_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let start = Instant::now();
    let (out, code) = run_jq_null(
        "[range(50000)] | . as $a | [range(200) | ($a | first), ($a | last), ($a | nth(5)), ($a | has(5)), ($a | length > 5)] | length",
        &["-c"],
    )?;
    let took = start.elapsed();
    assert_eq!((out.trim(), code), ("1000", 0));
    assert!(took < Duration::from_secs(15), "{took:?}");
    Ok(())
}
