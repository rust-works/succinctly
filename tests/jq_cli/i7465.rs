//! #7465: a path component's key (the `"a"` of `.a`, the `0` of `.[0]`) is one `jv` per program
//! site in jq 1.7.1, as `gen_index(gen_noop(), gen_const(k))` loads it with `LOADK`.
//!
//! So the key one site appends at two elements is the same `jv`, and `path($k)` accepts it:
//! `[.[] | path(.a)[0]] | .[0] as $k | .[1] | path($k)` is `[]`. Two sites of the same text are two
//! `jv`s and are refused, and a slice's key is built at each evaluation, so it is never identical.
//! The rows are a generated matrix (each component in eight shapes, on two documents) captured
//! from `/usr/bin/jq` 1.7.1, which jq 1.8.2 answers the same; a negative index (`.[-1]`, whose
//! `-1` jq 1.8 negates to a fresh literal, #7453) and the rows whose error jq 1.8 rewords are left
//! out.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

