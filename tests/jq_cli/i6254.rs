//! #6254: Oniguruma lets several groups share a name, and `\k<name>` then compares the text of the last
//! of them that is set, then the one before it, and so on, never giving a match back. A group set after
//! the reference is not one of them, and an unset group is skipped. `fancy-regex` resolved the name to one
//! group, so `(?<n>a)(?<n>b)\k<n>` missed `aba`. Every row was captured from jq 1.7.1 (`/usr/bin/jq -n -r`)
//! as the matches with each match's captures (name, string, offset).

