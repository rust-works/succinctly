#[test]
fn test_depth_refusal_marker_counts_jqs_reads_over_several_files_7573() -> Result<()> {
    let dir = tempfile::tempdir()?;
    std::fs::write(dir.path().join("b.json"), "1\n")?;
    let mut written = String::new();
    for (name, files, program, stdout, stderr, code) in ROWS {
        if written != *name {
            std::fs::write(dir.path().join("a.json"), shape(name))?;
            written = (*name).to_string();
        }
        let mut args = vec!["-c", "-n", program];
        args.extend_from_slice(files);
        let (got_out, got_err, got_code) = run_jq_in_dir(dir.path(), &args, None)?;
        let context = format!("{name} {files:?} {program}");
        assert_eq!(got_out, *stdout, "stdout: {context}");
        assert_eq!(got_err, *stderr, "stderr: {context}");
        assert_eq!(got_code, *code, "exit status: {context}");
    }
    Ok(())
}
