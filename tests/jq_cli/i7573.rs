//! #7573: with `-n` and several files, a depth refusal on a first line longer than 4095 bytes is
//! named by the line jq has counted when it meets it, not by the line the file ends. jq reads a
//! file in 4095-byte `fgets` chunks and counts a line only when it reads the chunk that ends in the
//! break, so a refusal met in the first chunk of `a.json`, whose break is in a later one, is
//! `(at a.json:0)`. The route that moves a document's open tail onto the next file counted the whole
//! line instead (`(at a.json:1)`). Every row was captured from jq 1.7.1 (`/usr/bin/jq -c -n PROGRAM
//! FILES`); jq 1.8.2 has no 256-level parse depth limit (it reads on), so the limit and its marker
//! stay 1.7.1's (`docs/compliance/jq/limitations.md`). `a.json` is the shape named in the row,
//! `b.json` is `1\n`.

use anyhow::Result;

use crate::run_jq_in_dir;

fn shape(name: &str) -> String {
    let brackets = "[".repeat(300);
    match name {
        "long_first_line" => format!("{brackets}{}\n", " ".repeat(5000)),
        "fault_in_second_read" => format!("{}{brackets}{}\n", " ".repeat(4000), " ".repeat(1000)),
        "short_first_line" => format!("{brackets}\n"),
        "two_lines" => format!("{brackets}{}\n2\n", " ".repeat(5000)),
        "fault_in_third_read" => format!("{}{brackets}\n", " ".repeat(8190)),
        "bracket_after_first_read" => {
            format!("{}{brackets}{}\n", " ".repeat(4090), " ".repeat(2000))
        }
        other => panic!("no shape {other}"),
    }
}

