//! #7260: two shapes whose peak held a transient vector the size of the input. `sort`/`unique` over
//! an array of document numbers sort on each number's parsed value and index, not on a decoded copy of
//! every element beside a stable sort's scratch buffer; and a pipe that starts with `..` runs each node
//! through the rest of the pipe as the walk reaches it, where every node's cursor and then a result per
//! node were held before `numbers` (or any later stage) dropped most of them. These rows pin what must
//! not move with them: each number's own spelling and jq's exact literal order (ties in input order,
//! `unique` keeping the first spelling), the fallback for arrays that hold other values, `..`'s
//! pre-order, and an error part-way (raised, caught, suppressed, from a later document that does not
//! parse). Every expected text was captured from jq 1.7.1 (`/usr/bin/jq`).

use anyhow::Result;

