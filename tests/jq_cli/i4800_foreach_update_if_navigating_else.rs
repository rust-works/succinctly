//! #4800: a `foreach` UPDATE that is an `if` whose `then` branch is the caught foreign-`$x` `foreach` and whose `else`
//! branch navigates or computes (`else .a`, `else 3`, `else []`, `else error("x")`). `FE` is
//! `foreach (try ($x as {a:$a} | .)) as $y (.; .; .)`.

