#[test]
fn a_parsed_infinity_compares_as_a_literal_7469() -> Result<()> {
    let mut failures = Vec::new();
    for &(program, input, stdout, stderr, code) in ROWS {
        let got = run_jq_full(&["-c", program], Some(&format!("{input}\n")))?;
        if got != (stdout.to_string(), stderr.to_string(), code) {
            failures.push(format!("{program} on {input}: got {got:?}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} of {} rows differ from jq:\n{}",
        failures.len(),
        ROWS.len(),
        failures.join("\n")
    );
    Ok(())
}

/// The other routes to a parsed infinity: `fromjson`, `tonumber`, `--argjson` and `--jsonargs`.
#[test]
fn every_parse_of_infinity_is_a_literal_7469() -> Result<()> {
    let program = "[$x > 1e1000, $x == infinite, ([$x, 1e1000] | sort)]";
    let expected = "[true,true,[1E+1000,1.7976931348623157e+308]]\n";
    for args in [
        &["-nc", "--argjson", "x", "Infinity", program][..],
        &[
            "-nc",
            r#""Infinity" | fromjson as $x | [$x > 1e1000, $x == infinite, ([$x, 1e1000] | sort)]"#,
        ],
        &[
            "-nc",
            r#""Infinity" | tonumber as $x | [$x > 1e1000, $x == infinite, ([$x, 1e1000] | sort)]"#,
        ],
        &[
            "-nc",
            "$ARGS.positional[0] as $x | [$x > 1e1000, $x == infinite, ([$x, 1e1000] | sort)]",
            "--jsonargs",
            "Infinity",
        ],
    ] {
        assert_eq!(
            run_jq_full(args, None)?,
            (expected.to_string(), String::new(), 0),
            "{args:?}"
        );
    }
    Ok(())
}
