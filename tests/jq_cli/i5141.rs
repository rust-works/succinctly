//! #5141: a `reduce` whose source moves jq's register, with an UPDATE that destructures `.` in an output it then discards.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// `reduce SRC as $i (.; (. as {b:$q} | 1), .)` with a SRC that navigates (`.a`, `..`): jq's register sits on the source's
// element for the whole step, so the UPDATE's `. as {b:$q}` indexes the accumulator, which is not the register, and raises
// `Invalid path expression near attempt to access element "b" of ..`. A `reduce` keeps only the last output of UPDATE,
// and the final `.` passes the final check, so the raise of the discarded item was never modelled: `path` answered `[]`
// and `|=`, `=` and `del` wrote where jq raises. `update_definitely_navigates` read no bind of `.` as navigation, so
// the step was resolved as if the accumulator were the register (`reduce_update_at_register`). A destructuring bind of `.`
// on a path that always runs now counts (`update_binds_accumulator`), and so do the builtins jq defines with `.[..]` on their
// input (`map`, `add`, `first`, `last`, `nth`, `flatten`, `join`); a source
// that moves nothing (`(1,2)`) is unchanged.

/// #5141: the issue's rows and the wrappers a comma sits in (`if`, `first`, `limit`, `label`, a pipe tail), under `path`,
/// `|=` and `del`, with the controls that answer (a source that moves nothing, a `try`, a bind of `null`, a `?//` chain, a
/// `foreach` UPDATE, a nested `reduce`). Every row captured from `/usr/bin/jq` 1.7.1 (stdout, exit code, message), both
/// routes.
#[test]
