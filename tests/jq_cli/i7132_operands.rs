/// The cost is the shape of the stages and not a timing: six stages, each its own `range | $a | STAGE`
/// loop or fold, over a 50,000-element array the filter computed, 200 calls each. Through the bridge
/// each call wrote the array out and indexed it again: 57 s for this program on the unoptimized binary
/// before, 0.1 s after, so the bound is far from both.
#[test]
fn operators_over_reads_of_a_bound_array_do_not_rewrite_it_per_call_7132() -> Result<()> {
    let start = Instant::now();
    let (out, code) = run_jq_null(
        "[range(50000)] as $a | ([range(200) | $a | .[0] + .[1]] + [range(200) | $a | first > 1] + [range(200) | $a | first // 0] + [range(200) | $a | first + 1] + [range(200) as $i | $a | .[$i] + 1]) | length, reduce range(200) as $i (0; . + ($a | .[0] + .[1]))",
        &["-c"],
    )?;
    let took = start.elapsed();
    assert_eq!((out.as_str(), code), ("1000\n200\n", 0));
    assert!(took < Duration::from_secs(15), "{took:?}");
    Ok(())
}
