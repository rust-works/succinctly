#[test]
fn a_malformed_bom_is_raised_on_the_stream_routes_7603() -> Result<()> {
    let dir = tempfile::tempdir()?;
    for (name, bytes) in [
        ("b1.json", &b"\xef1\n"[..]),
        ("ok.json", b"[1]\n"),
        ("e.json", b""),
        ("e1.json", b"\xef"),
        ("e2.json", b"1\n"),
        ("e3.json", b"\xbb2\n"),
    ] {
        std::fs::write(dir.path().join(name), bytes)?;
    }
    for &(stdin, args, stdout, stderr, code) in ROWS {
        let mut child = std::process::Command::new(env!("CARGO_BIN_EXE_succinctly"))
            .arg("jq")
            .args(args)
            .current_dir(dir.path())
            .env("LC_ALL", "C")
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()?;
        {
            use std::io::Write;
            let mut pipe = child.stdin.take().expect("piped");
            // A run that stops reading early closes the pipe: not a failure of the test.
            let _ = pipe.write_all(stdin);
        }
        let output = child.wait_with_output()?;
        assert_eq!(
            (
                String::from_utf8_lossy(&output.stdout).as_ref(),
                String::from_utf8_lossy(&output.stderr).as_ref(),
                output.status.code()
            ),
            (stdout, stderr, Some(code)),
            "{stdin:x?} {args:?}"
        );
    }
    Ok(())
}
