//! #6303: a comment right after a quantifier, then a second repeat operator, repeats the quantified item in
//! Oniguruma (`b*(?#)*` is `(?:b*)*`, `b+(?#)?` is `(?:b+)?` and not the lazy `b+?`). The comment was kept,
//! so the engines repeated the comment, which has no empty way of its own, and a loop around it
//! (`(?:b*(?#)*|a)+`) matched `"bab"` whole where jq 1.7.1 answers `b`, `""`, `b`, `""`. A greedy `*`, `+` or
//! `?` that ends the item and is followed, past the comments, by a greedy `*`, `+` or `?` that nothing
//! quantifies is now the one quantifier with the same language, and the comment is left out. Every row was
//! captured from jq 1.7.1 (`/usr/bin/jq -n`). Left out: `b*(?#){2}`, a repeat of a repeat by an interval, which
//! still differs (`docs/compliance/jq/limitations.md`).

use anyhow::Result;

use crate::run_jq_full;

fn answer(pattern: &str, input: &str, flags: &str) -> Result<String> {
    let program = format!(
        r#""{input}" | [match("{}";"{flags}") | [.offset, .length, .string]]"#,
        pattern.replace('\\', "\\\\")
    );
    let (stdout, stderr, code) = run_jq_full(&["-nc", &program], None)?;
    assert_eq!(code, 0, "{pattern} on {input}: stderr={stderr:?}");
    Ok(stdout.trim_end().to_string())
}

