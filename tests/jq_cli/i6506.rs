//! #6506: a way of a repeated body that starts with a capture group around a zero-width anchor, then an
//! item that can match nothing (`(\z)(\w*)`), is listed as the way that consumes and the exit the
//! anchor opens, as the other order is (#6492): the group is set by the way that consumes, too, and
//! by the empty way at the exit. Every row was captured from jq 1.7.1.

use anyhow::Result;

use crate::run_jq_full;

#[test]
fn a_captured_anchor_before_a_nullable_item_answers_as_jq_does_6506() -> Result<()> {
    for (pattern, input, expected) in [
        ("(?:(a)|(\\z)b*)+", "cba", "[[2,\"a\",[\"a\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "abc", "[[0,\"a\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "aab", "[[0,\"aa\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "ba", "[[1,\"a\",[\"a\",\"\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "ab", "[[0,\"a\",[\"a\",null]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "", "[[0,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\z)b*)+", "a b", "[[0,\"a\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "cba", "[[0,\"\",[\"\",\"\"]],[2,\"a\",[\"a\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "abc", "[[0,\"\",[\"\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "aab", "[[0,\"aa\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "ba", "[[0,\"ba\",[\"a\",\"\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "ab", "[[0,\"\",[\"\",\"\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*){2}", "", "[]"),
        ("(?:(a)|(\\b)b*){2}", "a b", "[[0,\"a\",[\"a\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"b\",[null,\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "cba", "[[0,\"cba\",[\"a\",\"\",\"cb\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "abc", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "aab", "[[0,\"aa\",[\"a\",null,null]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "ba", "[[0,\"ba\",[\"a\",\"\",\"b\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "ab", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\A)(\\w*)){2}", "a b", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "cba", "[[1,\"ba\",[\"a\",\"\",\"b\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "abc", "[[0,\"abc\",[\"a\",\"\",\"bc\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "aab", "[[0,\"aa\",[\"a\",null,null]],[2,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "ba", "[[1,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "ab", "[[0,\"ab\",[\"a\",\"\",\"b\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\B)(\\w*)){2,3}?", "a b", "[]"),
        ("(?:(a)|(\\z)(\\w*))*", "cba", "[[0,\"\",[\"\",\"\",\"\"]],[1,\"\",[\"\",\"\",\"\"]],[2,\"a\",[\"a\",\"\",\"\"]],[3,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "abc", "[[0,\"a\",[\"a\",null,null]],[1,\"\",[\"\",\"\",\"\"]],[2,\"\",[\"\",\"\",\"\"]],[3,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "aab", "[[0,\"aa\",[\"a\",null,null]],[2,\"\",[\"\",\"\",\"\"]],[3,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "ba", "[[0,\"\",[\"\",\"\",\"\"]],[1,\"a\",[\"a\",\"\",\"\"]],[2,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "ab", "[[0,\"a\",[\"a\",null,null]],[1,\"\",[\"\",\"\",\"\"]],[2,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\z)(\\w*))*", "a b", "[[0,\"a\",[\"a\",null,null]],[1,\"\",[\"\",\"\",\"\"]],[2,\"\",[\"\",\"\",\"\"]],[3,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "cba", "[[0,\"\",[\"\",\"\"]],[2,\"a\",[\"a\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "abc", "[[0,\"a\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "aab", "[[0,\"aa\",[\"a\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "ba", "[[0,\"ba\",[\"a\",\"\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "ab", "[[0,\"a\",[\"a\",null]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(\\b)b*)+", "", "[]"),
        ("(?:(a)|(\\b)b*)+", "a b", "[[0,\"a\",[\"a\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"b\",[null,\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\z)|a)*", "cba", "[[0,\"\",[\"\"]],[1,\"\",[\"\"]],[2,\"a\",[\"\"]],[3,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "abc", "[[0,\"a\",[null]],[1,\"\",[\"\"]],[2,\"\",[\"\"]],[3,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "aab", "[[0,\"aa\",[null]],[2,\"\",[\"\"]],[3,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "ba", "[[0,\"\",[\"\"]],[1,\"a\",[\"\"]],[2,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "ab", "[[0,\"a\",[null]],[1,\"\",[\"\"]],[2,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "", "[[0,\"\",[\"\"]]]"),
        ("(?:(\\z)|a)*", "a b", "[[0,\"a\",[null]],[1,\"\",[\"\"]],[2,\"\",[\"\"]],[3,\"\",[\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "cba", "[[0,\"\",[\"\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"a\",[null,\"a\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "abc", "[[0,\"\",[\"\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"\",[\"\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "aab", "[[0,\"\",[\"\",\"\"]],[1,\"a\",[null,\"a\"]],[2,\"\",[\"\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "ba", "[[0,\"ba\",[\"\",\"a\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "ab", "[[0,\"\",[\"\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "", "[[0,\"\",[\"\",\"\"]]]"),
        ("(?:(\\A)b?|(a))*", "a b", "[[0,\"\",[\"\",\"\"]],[1,\"\",[\"\",\"\"]],[2,\"\",[\"\",\"\"]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "cba", "[[0,\"cba\",[\"\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "abc", "[[0,\"abc\",[\"\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "aab", "[[0,\"aab\",[\"\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "ba", "[[0,\"ba\",[\"\",null]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "ab", "[[0,\"ab\",[\"\",null]],[2,\"\",[\"\",\"\"]]]"),
        ("(?:(\\b)\\w*|(a)){2,}", "", "[]"),
        ("(?:(\\b)\\w*|(a)){2,}", "a b", "[[0,\"a\",[\"\",null]],[1,\"\",[\"\",\"\"]],[2,\"b\",[\"\",null]],[3,\"\",[\"\",\"\"]]]"),
        ("(?:(a)|(^)(\\w*))+", "cba", "[[0,\"cba\",[null,\"\",\"cba\"]]]"),
        ("(?:(a)|(^)(\\w*))+", "abc", "[[0,\"a\",[\"a\",null,null]]]"),
        ("(?:(a)|(^)(\\w*))+", "aab", "[[0,\"aa\",[\"a\",null,null]]]"),
        ("(?:(a)|(^)(\\w*))+", "ba", "[[0,\"ba\",[null,\"\",\"ba\"]]]"),
        ("(?:(a)|(^)(\\w*))+", "ab", "[[0,\"a\",[\"a\",null,null]]]"),
        ("(?:(a)|(^)(\\w*))+", "", "[[0,\"\",[\"\",\"\",\"\"]]]"),
        ("(?:(a)|(^)(\\w*))+", "a b", "[[0,\"a\",[\"a\",null,null]]]"),
    ] {
        let (stdout, _, status) = run_jq_full(
            &[
                "-nc",
                "--arg",
                "s",
                input,
                "--arg",
                "p",
                pattern,
                r#"[$s | match($p; "g") | [.offset, .string, (.captures | map(.string))]]"#,
            ],
            None,
        )?;
        assert_eq!(
            (stdout.trim_end(), status),
            (expected, 0),
            "{pattern} on {input:?}"
        );
    }
    Ok(())
}
