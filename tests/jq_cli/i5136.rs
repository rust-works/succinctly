//! #5136: a `reduce` UPDATE of a handler-less `try`/`?` around a bind of `.` that ends on `.`.

use anyhow::Result;

use crate::assert_path_rows_both_routes_3749;

// `reduce SRC as $i (INIT; try (. as {b:$q} | .))`: while the bind passes the UPDATE emits the accumulator's own node, and
// when it raises the `try` empties the UPDATE and the next state is `null`. `update_returns_its_input` read a bind of `.`
// that returns it (#3953) but not through a `try`/`?`, so the UPDATE was read as computing a value and the final
// emission was refused (`with result <accumulator>`): `path`, `del`, `|=` and `=` failed where jq answers, and
// `[path(..)?]` lost the path.

/// #5136: the issue's rows, the controls where the pattern raises (the state becomes `null`, as in jq), and rows of a
/// differential grid (document x bind site x pattern x body x source x INIT x wrapper x context) that `main` refused or
/// answered wrongly, with nested folds, `first`/`label`/`limit`/`if`/`//` around the `try`, and the `catch` handler form as a
/// control. Every row captured from `/usr/bin/jq` 1.7.1 (stdout, exit code, message), both routes.
#[test]
#[allow(clippy::literal_string_with_formatting_args)] // jq object patterns read like format arguments
