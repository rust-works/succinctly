/// `format("urid")` keeps jq 1.7.1's answer (the pin), where `@urid` follows 1.8.2: the split the
/// format table records.
#[test]
fn format_urid_keeps_the_pinned_answer_6726() -> Result<()> {
    let (stdout, stderr, code) = run_jq_full(&["-c", "format(\"urid\")"], Some("\"%41\""))?;
    assert_eq!(
        (stdout.as_str(), stderr.as_str(), code),
        (
            "",
            "jq: error (at <stdin>:0): urid is not a valid format\n",
            5
        )
    );
    Ok(())
}
