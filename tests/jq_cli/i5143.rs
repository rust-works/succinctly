// #5141 made a destructuring bind of `.` and the builtins that index on every accumulator (`map`, `add`, `first`, ..) navigate
// it; these are the members whose indexing depends on the accumulator or on a condition: `reverse` (`.[length - 1 -
// range(0;length)]`) and `transpose` (`$in[$i][$j]` over the largest length, its `map(length)` in a subexpression) index
// only a container with something to index, `index`/`rindex`/`indices` (`.[[$i]]`) all but a string, `. as $z | $z.b` and
