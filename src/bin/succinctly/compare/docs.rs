/// The per-group geomean speedups [`GUIDE_DOC`] quotes: one row per group, one column per committed
/// platform run, built from the committed `docs/compare/jq-<platform>.json` files alone (#6916).
pub fn categories_block(runs: &[(String, Value)]) -> String {
    let mut header: Vec<String> = vec!["Group".into(), "Queries".into()];
    header.extend(runs.iter().map(|(p, v)| {
        format!(
            "[{}](../compare/jq-{p}.md)",
            v["env"]["system"]["cpu"].as_str().unwrap_or("?")
        )
    }));
    let rows: Vec<Vec<String>> = QUERY_GROUPS
        .iter()
        .map(|(name, queries, keep)| {
            let mut row = vec![(*name).to_string(), (*queries).to_string()];
            row.extend(runs.iter().map(|(_, v)| {
                let xs: Vec<f64> = v["perf"]
                    .as_array()
                    .map_or(&[][..], Vec::as_slice)
                    .iter()
                    .filter(|r| keep(r["query"].as_str().unwrap_or("")))
                    .filter_map(|r| r["speedup_primary"].as_f64())
                    .collect();
                geomean(&xs).map_or_else(|| "n/a".into(), |g| format!("{g:.2}x"))
            }));
            row
        })
        .collect();
    let header: Vec<&str> = header.iter().map(String::as_str).collect();
    table(&header, &rows, 2)
}

/// [`GUIDE_DOC`] with its `compare:jq-categories` block regenerated from every run.
pub fn patch_guide(doc: &str, runs: &[(String, Value)]) -> Result<String> {
    patch_block(doc, "jq-categories", &categories_block(runs))
        .map_err(|e| anyhow::anyhow!("{GUIDE_DOC}: {e} (the block holds the by-category table)"))
}

/// [`SUMMARY_DOC`] with its `compare:jq-summary` block regenerated from every run.
pub fn patch_summary(doc: &str, runs: &[(String, Value)]) -> Result<String> {
    patch_block(doc, "jq-summary", &summary_block(runs)).map_err(|e| {
        anyhow::anyhow!("{SUMMARY_DOC}: {e} (the block sits in the Performance Summary section)")
    })
}

/// The identity (`.`) table [`README_DOC`] quotes: one `####` section per committed
/// platform run, one row per 10 MB input shape, built from the committed
/// `docs/compare/jq-<platform>.json` alone (#6871). Rows are ordered by speedup,
/// fastest first, and only a row whose outputs matched (so it was timed) appears.
pub fn identity_block(runs: &[(String, Value)]) -> String {
    const TIER: &str = "10mb";
    let mut s = String::new();
    for (_, v) in runs {
        let rows: &[Value] = v["perf"].as_array().map_or(&[], Vec::as_slice);
        let mut picked: Vec<(&Value, f64)> = rows
            .iter()
            .filter(|r| r["query"] == "identity" && r["tier"] == TIER)
            .filter_map(|r| Some((r, r["speedup_primary"].as_f64()?)))
            .collect();
        if picked.is_empty() {
            continue;
        }
        picked.sort_by(|a, b| b.1.total_cmp(&a.1));
        let reference = picked[0].0["tools"]
            .get(1)
            .and_then(|t| t["tool"].as_str())
            .unwrap_or("jq");
        let ms = |r: &Value, i: usize| {
            time_ms(r, i).map_or_else(|| "n/a".into(), |x| format!("{x:.1}ms"))
        };
        let mb = |r: &Value, i: usize| {
            r["tools"]
                .get(i)
                .and_then(|t| t["peak_rss_kb"].as_f64())
                .map_or_else(|| "n/a".into(), |kb| format!("{:.0} MB", kb / 1024.0))
        };
        let cells: Vec<Vec<String>> = picked
            .iter()
            .map(|&(r, speedup)| {
                let dagger = if r["ratio_from_min"].as_bool() == Some(true) {
                    "†"
                } else {
                    ""
                };
                let input = r["input"].as_str().unwrap_or("?");
                vec![
                    format!("**{}**", input.strip_suffix("-10mb").unwrap_or(input)),
                    ms(r, 1),
                    ms(r, 0),
                    format!("{speedup:.1}x{dagger}"),
                    mb(r, 1),
                    mb(r, 0),
                    r["rss_ratio_primary"]
                        .as_f64()
                        .map_or_else(|| "n/a".into(), |x| format!("{x:.2}x")),
                ]
            })
            .collect();
        let _ = writeln!(
            s,
            "#### {} (10 MB files, {reference})\n",
            v["env"]["system"]["cpu"].as_str().unwrap_or("?")
        );
        s.push_str(&table(
            &[
                "Pattern",
                reference,
                "succinctly",
                "Speedup",
                &format!("{reference} Mem"),
                "succ Mem",
                "Mem Ratio",
            ],
            &cells,
            1,
        ));
        s.push('\n');
    }
    let _ = write!(
        s,
        "Generated by `--write-docs` from [docs/compare/](docs/compare/jq.md); do not edit. \
         Tools are interleaved within each repetition and a row is timed only where the \
         outputs are identical. Times are medians, except where marked †: both times and \
         the ratio are then each tool's fastest run, which noise moves least on a long row. \
         Speedup is the reference's time over `succinctly jq`'s; Mem is \
         peak RSS, and the ratio is `succinctly jq`'s over the reference's."
    );
    s
}

/// [`README_DOC`] with its `compare:jq-identity` block regenerated from every run.
pub fn patch_readme(doc: &str, runs: &[(String, Value)]) -> Result<String> {
    patch_block(doc, "jq-identity", &identity_block(runs)).map_err(|e| {
        anyhow::anyhow!("{README_DOC}: {e} (the block sits under \"jq Comparison: Identity\")")
    })
}

