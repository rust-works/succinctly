//! The committed copies of a run: `docs/compare/jq-<platform>.{md,json}` and the
//! index `docs/compare/jq.md` built from every platform's json (#5409).

use serde_json::Value;

pub const PLATFORM: &str = const_format();

const fn const_format() -> &'static str {
    if cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        "macos-aarch64"
    } else if cfg!(all(target_os = "macos", target_arch = "x86_64")) {
        "macos-x86_64"
    } else if cfg!(all(target_os = "linux", target_arch = "aarch64")) {
        "linux-aarch64"
    } else if cfg!(all(target_os = "linux", target_arch = "x86_64")) {
        "linux-x86_64"
    } else if cfg!(target_os = "windows") {
        "windows"
    } else {
        "other"
    }
}

pub const HEADER: &str =
    "<!-- Generated by `succinctly dev compare jq --write-docs`; do not edit. -->\n\n";

fn geomean(xs: &[f64]) -> Option<f64> {
    (!xs.is_empty()).then(|| (xs.iter().map(|x| x.ln()).sum::<f64>() / xs.len() as f64).exp())
}

fn count(v: &Value, key: &str, field: &str, want: &str) -> (usize, usize) {
    let rows = v
        .get(key)
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let ok = rows.iter().filter(|r| r[field] == want).count();
    (ok, rows.len())
}

/// One row of the index from a platform's results.
pub fn index_row(platform: &str, v: &Value) -> String {
    let cpu = v["env"]["system"]["cpu"].as_str().unwrap_or("?");
    let commit = v["env"]["git"]["commit_short"].as_str().unwrap_or("?");
    let (cli_ok, cli_all) = count(v, "cli", "verdict", "match");
    let up: (usize, usize) = v["differential"].as_array().map_or((0, 0), |a| {
        a.iter().fold((0, 0), |(o, t), s| {
            (
                o + s["matching"].as_u64().unwrap_or(0) as usize,
                t + s["total"].as_u64().unwrap_or(0) as usize,
            )
        })
    });
    let builtins = v["features"]["matching_pct"]
        .as_f64()
        .map_or_else(|| "n/a".into(), |p| format!("{p:.1}%"));
    let speeds: Vec<f64> = v["perf"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter_map(|r| r["speedup_primary"].as_f64())
                .collect()
        })
        .unwrap_or_default();
    let speed = geomean(&speeds).map_or_else(|| "n/a".into(), |g| format!("{g:.2}x"));
    format!(
        "| [{platform}](jq-{platform}.md) | {cpu} | `{commit}` | {builtins} | {cli_ok}/{cli_all} | {}/{} | {speed} |",
        up.0, up.1
    )
}

pub fn index(rows: &[(String, Value)]) -> String {
    let mut s = String::from(HEADER);
    s.push_str("# jq vs succinctly jq\n\n");
    s.push_str(
        "Generated comparison of `jq` 1.7.1 (primary) and 1.8.1 (secondary) with `succinctly jq`: \
         features, correctness, performance, memory, robustness and operational properties. \
         Reproduce with `succinctly dev compare jq`; see [comparison/jq/README.md](../../comparison/jq/README.md). \
         Each platform has its own report; memory-bound effects do not port across architectures, \
         so no figure is extrapolated between them.\n\n",
    );
    s.push_str("| Platform | CPU | Commit | Builtins agreeing | CLI probes | Upstream jq tests | Geomean speedup |\n");
    s.push_str("|----------|-----|--------|-------------------|------------|-------------------|-----------------|\n");
    for (p, v) in rows {
        s.push_str(&index_row(p, v));
        s.push('\n');
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn run() -> Value {
        json!({
            "env": {"system": {"cpu": "Test CPU"}, "git": {"commit_short": "abc1234"}},
            "features": {"matching_pct": 98.1},
            "cli": [{"verdict": "match"}, {"verdict": "differs"}],
            "differential": [{"matching": 3, "total": 4}, {"matching": 1, "total": 1}],
            "perf": [{"speedup_primary": 2.0}, {"speedup_primary": 8.0}, {"speedup_primary": null}]
        })
    }

    #[test]
    fn index_row_summarises_a_run() {
        assert_eq!(
            index_row("linux-x86_64", &run()),
            "| [linux-x86_64](jq-linux-x86_64.md) | Test CPU | `abc1234` | 98.1% | 1/2 | 4/5 | 4.00x |"
        );
    }

    #[test]
    fn a_sparse_run_renders_placeholders_not_a_panic() {
        let row = index_row("p", &json!({}));
        assert!(row.contains("n/a") && row.contains("0/0"));
    }

    #[test]
    fn the_index_is_marked_generated_and_lists_every_platform() {
        let s = index(&[("a".into(), run()), ("b".into(), run())]);
        assert!(s.starts_with("<!-- Generated"));
        assert_eq!(s.matches("| [").count(), 2);
    }

    #[test]
    fn the_platform_name_is_known() {
        assert_ne!(PLATFORM, "");
    }
}
