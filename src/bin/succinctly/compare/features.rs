//! Dimension A: language and builtin coverage (#5409).
//!
//! The inventory is the reference's own `builtins`, never succinctly's, so
//! succinctly's coverage is not what defines "what jq has". Each
//! `name/arity` is probed on a fixed input set under `try ... catch "E"`
//! (error *wording* is the error-probe suite's job): jq's compile-time
//! `is not defined` from succinctly is `not-implemented`; the same stdout and
//! exit is `match`; anything else is `differs`.

use super::exec::{exec, Exec};
use super::harness::Tool;
use anyhow::{bail, Result};
use serde::Serialize;
use std::collections::BTreeSet;
use std::path::Path;

/// One value per jq type, plus a number with a fraction, nested arrays and a
/// timestamp for the date builtins.
const INPUTS: &str =
    "null\n1\n-1.5\n\"a\"\n[1,2,3]\n{\"a\":1}\n[[1,2],[3]]\n\"2015-03-05T23:51:47Z\"\n";

/// Builtins that cannot be probed deterministically, and why.
const NOT_PROBED: &[(&str, &str)] = &[
    ("halt/0", "ends the process"),
    ("halt_error/0", "ends the process"),
    ("halt_error/1", "ends the process"),
    ("input/0", "consumes the probe's own input"),
    ("inputs/0", "consumes the probe's own input"),
    ("debug/0", "writes to stderr"),
    ("debug/1", "writes to stderr"),
    ("stderr/0", "writes to stderr"),
    ("now/0", "non-deterministic"),
    ("env/0", "host environment"),
    ("until/2", "does not terminate on the default argument"),
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum Status {
    Match,
    Differs,
    NotImplemented,
    NotProbed,
}

#[derive(Debug, Clone, Serialize)]
pub struct FeatureRow {
    pub id: String,
    pub status: Status,
    pub note: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct FeatureSummary {
    pub reference: String,
    pub total: usize,
    pub probed: usize,
    pub matching: usize,
    pub differs: usize,
    pub not_implemented: usize,
    pub not_probed: usize,
    /// (matching + differs) / probed: the share of probed builtins succinctly defines.
    pub implemented_pct: f64,
    /// matching / probed: the share that also agrees with the reference.
    pub matching_pct: f64,
    pub rows: Vec<FeatureRow>,
}

/// The figures `docs/reference/jq-language.md` quotes, committed as
/// `docs/compare/jq-coverage.json` so a hermetic test can hold the prose to them.
#[derive(Debug, Clone, PartialEq, Serialize, serde::Deserialize)]
pub struct Coverage {
    pub reference: String,
    pub total: usize,
    pub probed: usize,
    pub matching: usize,
    pub implemented_pct: f64,
    pub matching_pct: f64,
}

pub const DOC_START: &str = "<!-- compare:builtins -->";
pub const DOC_END: &str = "<!-- /compare:builtins -->";

impl From<&FeatureSummary> for Coverage {
    fn from(f: &FeatureSummary) -> Self {
        Self {
            reference: f.reference.clone(),
            total: f.total,
            probed: f.probed,
            matching: f.matching,
            implemented_pct: f.implemented_pct,
            matching_pct: f.matching_pct,
        }
    }
}

impl Coverage {
    pub fn sentence(&self) -> String {
        format!(
            "Of the {} builtins {} lists, {} were probed: {:.1}% are defined by succinctly and {:.1}% \
             also give {}'s output ({}/{}). Generated by `succinctly dev compare jq`.",
            self.total, self.reference, self.probed, self.implemented_pct, self.matching_pct,
            self.reference, self.matching, self.probed
        )
    }
}

/// Replace the text between the doc's markers with `cov`'s sentence.
pub fn patch_doc(doc: &str, cov: &Coverage) -> Result<String> {
    let (Some(a), Some(b)) = (doc.find(DOC_START), doc.find(DOC_END)) else {
        bail!("doc has no {DOC_START} ... {DOC_END} block");
    };
    if b < a {
        bail!("doc markers are out of order");
    }
    Ok(format!(
        "{}{DOC_START}\n{}\n{}",
        &doc[..a],
        cov.sentence(),
        &doc[b..]
    ))
}

/// `name/arity` of every builtin the reference lists, sorted.
pub fn inventory(reference: &Tool, cwd: &Path) -> Result<Vec<String>> {
    let args = ["-n", "-r", "builtins|.[]"].map(String::from);
    let out = exec(reference, &args, "", cwd)?;
    if out.exit != Some(0) {
        bail!("`{}` could not list its builtins", reference.name);
    }
    let set: BTreeSet<String> = String::from_utf8(out.stdout)?
        .lines()
        .map(String::from)
        .collect();
    Ok(set.into_iter().collect())
}

pub fn program(id: &str) -> String {
    let (name, arity) = id.rsplit_once('/').expect("name/arity");
    let n: usize = arity.parse().expect("arity");
    let call = if n == 0 {
        name.to_string()
    } else {
        format!("{name}({})", vec!["."; n].join(";"))
    };
    format!("[limit(8; try ({call}) catch \"E\")]")
}

fn classify(reference: &Exec, subject: &Exec) -> (Status, Option<String>) {
    if reference.timed_out && subject.timed_out {
        return (
            Status::NotProbed,
            Some("times out on the default probe".into()),
        );
    }
    if subject.is_undefined() && !reference.is_undefined() {
        return (Status::NotImplemented, None);
    }
    if reference.exit == subject.exit && reference.stdout == subject.stdout {
        (Status::Match, None)
    } else {
        let first = |e: &Exec| {
            String::from_utf8_lossy(&e.stdout)
                .lines()
                .next()
                .unwrap_or("")
                .chars()
                .take(80)
                .collect::<String>()
        };
        (
            Status::Differs,
            Some(format!(
                "exit {:?} vs {:?}; reference `{}`, succinctly `{}`",
                reference.exit,
                subject.exit,
                first(reference),
                first(subject)
            )),
        )
    }
}

pub fn probe_one(reference: &Tool, subject: &Tool, id: &str, cwd: &Path) -> Result<FeatureRow> {
    if let Some((_, why)) = NOT_PROBED.iter().find(|(n, _)| *n == id) {
        return Ok(FeatureRow {
            id: id.into(),
            status: Status::NotProbed,
            note: Some((*why).into()),
        });
    }
    let args = vec!["-c".to_string(), program(id)];
    let (status, note) = classify(
        &exec(reference, &args, INPUTS, cwd)?,
        &exec(subject, &args, INPUTS, cwd)?,
    );
    Ok(FeatureRow {
        id: id.into(),
        status,
        note,
    })
}

#[allow(clippy::cast_precision_loss)]
pub fn summarize(reference: &str, rows: Vec<FeatureRow>) -> FeatureSummary {
    let count = |s: Status| rows.iter().filter(|r| r.status == s).count();
    let (matching, differs) = (count(Status::Match), count(Status::Differs));
    let not_implemented = count(Status::NotImplemented);
    let probed = matching + differs + not_implemented;
    let pct = |n: usize| {
        if probed == 0 {
            0.0
        } else {
            (n as f64 * 1000.0 / probed as f64).round() / 10.0
        }
    };
    FeatureSummary {
        reference: reference.into(),
        total: rows.len(),
        probed,
        matching,
        differs,
        not_implemented,
        not_probed: count(Status::NotProbed),
        implemented_pct: pct(matching + differs),
        matching_pct: pct(matching),
        rows,
    }
}

/// Probe every builtin of `reference` (or only `only`, when given).
pub fn run(
    reference: &Tool,
    reference_id: &str,
    subject: &Tool,
    only: Option<&BTreeSet<String>>,
    cwd: &Path,
) -> Result<FeatureSummary> {
    let mut rows = vec![];
    for id in inventory(reference, cwd)? {
        if only.is_some_and(|s| !s.contains(&id)) {
            continue;
        }
        rows.push(probe_one(reference, subject, &id, cwd)?);
    }
    Ok(summarize(reference_id, rows))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn e(exit: i32, out: &str, err: &str) -> Exec {
        Exec {
            exit: Some(exit),
            stdout: out.into(),
            stderr: err.into(),
            timed_out: false,
        }
    }

    #[test]
    fn program_wraps_every_arity_in_a_bounded_try() {
        assert_eq!(program("length/0"), "[limit(8; try (length) catch \"E\")]");
        assert_eq!(program("sub/3"), "[limit(8; try (sub(.;.;.)) catch \"E\")]");
    }

    #[test]
    fn classification_distinguishes_the_three_outcomes() {
        let ok = e(0, "[1]", "");
        let undefined = e(3, "", "jq: error: f/0 is not defined at <top-level>");
        assert_eq!(classify(&ok, &ok).0, Status::Match);
        assert_eq!(classify(&ok, &undefined).0, Status::NotImplemented);
        assert_eq!(classify(&ok, &e(0, "[2]", "")).0, Status::Differs);
        assert_eq!(classify(&ok, &e(5, "[1]", "")).0, Status::Differs);
    }

    /// A reference that does not define the name is never "not implemented"
    /// by succinctly: both rejecting it is agreement, not a gap.
    #[test]
    fn both_rejecting_is_a_match() {
        let u = e(3, "", "f/0 is not defined");
        assert_eq!(classify(&u, &u).0, Status::Match);
    }

    fn cov() -> Coverage {
        Coverage {
            reference: "jq-1.7.1".into(),
            total: 10,
            probed: 8,
            matching: 6,
            implemented_pct: 100.0,
            matching_pct: 75.0,
        }
    }

    #[test]
    fn patching_replaces_only_the_marked_block() {
        let doc = format!("a\n{DOC_START}\nold\n{DOC_END}\nb\n");
        let out = patch_doc(&doc, &cov()).unwrap();
        assert!(out.starts_with("a\n") && out.ends_with(&format!("{DOC_END}\nb\n")));
        assert!(out.contains(&cov().sentence()) && !out.contains("old"));
        assert_eq!(patch_doc(&out, &cov()).unwrap(), out);
        assert!(patch_doc("no markers", &cov()).is_err());
    }

    /// The prose in the language reference is generated, so it must equal
    /// what the committed summary says; editing either alone fails here.
    #[test]
    fn language_reference_quotes_the_committed_summary() {
        let json = include_str!("../../../../docs/compare/jq-coverage.json");
        let cov: Coverage = serde_json::from_str(json).unwrap();
        let doc = include_str!("../../../../docs/reference/jq-language.md");
        assert_eq!(patch_doc(doc, &cov).unwrap(), doc);
    }

    #[test]
    fn percentages_come_from_the_rows() {
        let row = |id: &str, status| FeatureRow {
            id: id.into(),
            status,
            note: None,
        };
        let s = summarize(
            "jq-1.7.1",
            vec![
                row("a/0", Status::Match),
                row("b/0", Status::Differs),
                row("c/0", Status::NotImplemented),
                row("d/0", Status::Match),
                row("e/0", Status::NotProbed),
            ],
        );
        assert_eq!((s.total, s.probed, s.not_probed), (5, 4, 1));
        assert_eq!((s.implemented_pct, s.matching_pct), (75.0, 50.0));
    }
}
