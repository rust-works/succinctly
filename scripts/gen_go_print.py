#!/usr/bin/env python3
"""Regenerate src/jq/go_print.rs: the code points Go's strconv.Quote escapes, as the pinned yq writes them.

Go's `unicode.IsPrint` depends on the Unicode version of the Go release that built the binary, which
Python's `unicodedata` does not track, so the table is read from `yq -o=toml`, whose strings go through
`%q` (#6924). Needs `yq` (the pinned v4.53.3) on PATH.

    python3 scripts/gen_go_print.py > src/jq/go_print.rs
"""
import json
import subprocess
import sys

BATCH = 4096


def non_printable():
    cps = [c for c in range(0x80, 0x110000) if not 0xD800 <= c <= 0xDFFF]
    out = []
    for i in range(0, len(cps), BATCH):
        chunk = cps[i : i + BATCH]
        doc = {f"k{j}": chr(c) for j, c in enumerate(chunk)}
        run = subprocess.run(
            ["yq", "-p=json", "-o=toml", "."],
            input=json.dumps(doc, ensure_ascii=True).encode(),
            capture_output=True,
            check=True,
        )
        lines = run.stdout.decode("utf-8").split("\n")
        for j, c in enumerate(chunk):
            prefix = f'k{j} = "'
            assert lines[j].startswith(prefix), lines[j]
            if lines[j][len(prefix) :].startswith("\\"):
                out.append(c)
    return out


def ranges(cps):
    out = []
    for c in cps:
        if out and out[-1][1] + 1 == c:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def main():
    version = subprocess.run(["yq", "--version"], capture_output=True, text=True).stdout.strip().rsplit(" ", 1)[-1]
    table = ranges(non_printable())
    print("//! Which code points Go's `strconv.Quote` escapes (`unicode.IsPrint` is false), for `-o=toml` (#6924).")
    print("//!")
    print(f"//! Generated by `scripts/gen_go_print.py` from yq {version}; do not edit by hand.")
    print()
    print("/// Inclusive ranges of code points above U+007F that Go does not print as they are.")
    print(f"static NON_PRINTABLE: [(u32, u32); {len(table)}] = [")
    for lo, hi in table:
        print(f"    (0x{lo:X}, 0x{hi:X}),")
    print("];")
    print()
    print("/// Whether Go's `unicode.IsPrint` holds for `c`: a letter, mark, number, punctuation, symbol, or the")
    print("/// ASCII space.")
    print("pub(crate) fn is_print(c: char) -> bool {")
    print("    let code = c as u32;")
    print("    if code < 0x80 {")
    print("        return (0x20..0x7F).contains(&code);")
    print("    }")
    print("    NON_PRINTABLE")
    print("        .binary_search_by(|&(lo, hi)| {")
    print("            if code < lo {")
    print("                core::cmp::Ordering::Greater")
    print("            } else if code > hi {")
    print("                core::cmp::Ordering::Less")
    print("            } else {")
    print("                core::cmp::Ordering::Equal")
    print("            }")
    print("        })")
    print("        .is_err()")
    print("}")


if __name__ == "__main__":
    sys.exit(main())
