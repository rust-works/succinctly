#!/usr/bin/env python3
"""Generate src/jq/shell_nfkd.rs from the Unicode Character Database (#7092).

yq's `-o=shell` builds a variable name from a key by decomposing it with NFKD
(golang.org/x/text/unicode/norm) and then keeping `[A-Za-z0-9_]`, writing every other printable ASCII
character as `_` and dropping the rest.  Only a character whose decomposition holds an ASCII
character matters, so the table lists, for each such code point above U+007F, the text that rule
leaves of its NFKD: `é` is `e`, `ﬁ` is `fi`, `…` is `___`, a no-break space is `_`.

The decomposition is computed from the `Decomposition_Mapping` field of UnicodeData.txt, compatibility
mappings included, expanded recursively.  Hangul syllables decompose to jamo, which are all dropped.

Usage:
    curl -sSfL https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt -o /tmp/UnicodeData.txt
    python3 -I scripts/gen_shell_nfkd.py 15.0.0 /tmp/UnicodeData.txt > src/jq/shell_nfkd.rs
"""
import sys


def keep(ch):
    cp = ord(ch)
    if ch.isascii() and (ch.isalnum() or ch == "_"):
        return ch
    if 32 <= cp <= 126:
        return "_"
    return ""


def main():
    version, path = sys.argv[1], sys.argv[2]
    mapping = {}
    for line in open(path, encoding="utf-8"):
        fields = line.rstrip("\n").split(";")
        decomposition = fields[5]
        if decomposition:
            parts = decomposition.split()
            if parts[0].startswith("<"):
                parts = parts[1:]
            mapping[int(fields[0], 16)] = [int(p, 16) for p in parts]

    def nfkd(cp):
        if cp not in mapping:
            return [cp]
        out = []
        for part in mapping[cp]:
            out.extend(nfkd(part))
        return out

    entries = []
    for cp in range(0x80, 0x110000):
        if cp not in mapping:
            continue
        text = "".join(keep(chr(c)) for c in nfkd(cp))
        if text:
            entries.append((cp, text))

    # A run of consecutive code points whose single-letter results are consecutive too (the
    # mathematical alphanumerics, the circled and fullwidth letters) is one row.
    rows = []
    i = 0
    while i < len(entries):
        cp, text = entries[i]
        j = i
        if len(text) == 1:
            while (
                j + 1 < len(entries)
                and entries[j + 1][0] == entries[j][0] + 1
                and len(entries[j + 1][1]) == 1
                and ord(entries[j + 1][1]) == ord(entries[j][1]) + 1
                and entries[j + 1][1].isalnum() == text.isalnum()
            ):
                j += 1
        rows.append((cp, j - i + 1, text))
        i = j + 1

    print("// @generated by scripts/gen_shell_nfkd.py from UnicodeData.txt %s. Do not edit by hand;" % version)
    print("// see the script for how to regenerate (#7092).")
    print()
    print("/// The Unicode version of the table.")
    print("#[cfg(test)]")
    print('pub(super) const UNICODE_VERSION: &str = "%s";' % version)
    print()
    print("/// `(first code point, run length, text)`, sorted by code point: the code point `first + k` of a run")
    print("/// is the text's single character advanced by `k`; a run of one is the text itself.")
    print("pub(super) const ROWS: &[(u32, u32, &str)] = &[")
    for cp, count, text in rows:
        print('    (0x%x, %d, "%s"),' % (cp, count, text))
    print("];")


main()
