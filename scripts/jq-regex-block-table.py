#!/usr/bin/env python3
"""Generate `src/jq/regex_blocks.rs`, the Unicode block table behind `\\p{In_Basic_Latin}` (#6228).

    scripts/jq-regex-block-table.py [--jq /usr/bin/jq] [--write | --check]

Oniguruma reads `\\p{In_<Block>}` as the code points of a Unicode block; the `regex` crate has no block
table. The table is read from the oracle itself: the names are the `in...` strings in the jq binary
(Oniguruma is linked in statically), and each name's ranges come from running `match` over a string of
every scalar value, so the table is what that Oniguruma answers, not what some `Blocks.txt` says. The
names are normalized the way Oniguruma does (lower case, no blank, `_` or `-`).

`--write` rewrites the file, `--check` exits 1 when the file differs from what the oracle answers, and
with neither the file is printed. `inherited`, `initialpunctuation`, `inscriptionalpahlavi` and
`inscriptionalparthian` start with `in` but are a script and a general category, not blocks.
"""
import argparse
import json
import os
import re
import subprocess
import sys

NOT_BLOCKS = {"inherited", "initialpunctuation", "inscriptionalpahlavi", "inscriptionalparthian"}
PROG = '([range(0;55296),range(57344;1114112)]|implode) as $all | [$all|match("\\\\p{%s}+";"g")|[.offset,.length]]'


def scalar(offset):
    """The code point at `offset` in the string of every scalar value (the surrogates are skipped)."""
    return offset if offset < 0xD800 else offset + 0x800


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jq", default="/usr/bin/jq")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()

    strings = subprocess.run(["strings", "-a", args.jq], capture_output=True, text=True, check=True).stdout
    names = sorted({s for s in map(str.strip, strings.splitlines()) if re.fullmatch(r"in[a-z0-9]+", s)} - NOT_BLOCKS)
    table = []
    for name in names:
        run = subprocess.run([args.jq, "-n", "-c", PROG % name], capture_output=True, text=True)
        if run.returncode:
            continue  # a string that merely looks like a name
        ranges = []
        for offset, length in json.loads(run.stdout):
            lo, hi = scalar(offset), scalar(offset + length - 1)
            if lo < 0xD800 <= hi:
                sys.exit("%s: a range spans the surrogates" % name)
            ranges.append((lo, hi))
        table.append((name, ranges))

    out = [
        "//! The Unicode block names Oniguruma reads as `\\p{In_<Block>}` (#6228), generated by",
        "//! `scripts/jq-regex-block-table.py` from the pinned jq. Do not edit by hand.",
        "",
        "/// Each block's normalized name (lower case, without blanks, `_` and `-`) and its inclusive code",
        "/// point ranges, sorted by name. The three surrogate blocks hold no scalar value, so they are",
        "/// empty; `innoblock` is the code points no block holds.",
        "pub(super) static BLOCKS: &[(&str, &[(u32, u32)])] = &[",
    ]
    for name, ranges in table:
        body = ", ".join("(0x%X, 0x%X)" % r for r in ranges)
        line = '    ("%s", &[%s]),' % (name, body)
        out.append(line)
    out += ["];", ""]
    # rustfmt wraps `innoblock`'s long line, so `--check` compares what the formatter would leave.
    text = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"], input="\n".join(out), capture_output=True, text=True, check=True
    ).stdout
    text = text.split("\n", 1)[1] if text.startswith("<stdin>") else text
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src/jq/regex_blocks.rs")
    if args.write:
        open(path, "w").write(text)
        print("wrote %d blocks to %s" % (len(table), path))
    elif args.check:
        if open(path).read() != text:
            print("src/jq/regex_blocks.rs differs from what %s answers" % args.jq, file=sys.stderr)
            sys.exit(1)
        print("src/jq/regex_blocks.rs matches (%d blocks)" % len(table))
    else:
        print(text)


if __name__ == "__main__":
    main()
