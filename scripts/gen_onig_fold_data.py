#!/usr/bin/env python3
"""Generate src/jq/onig_fold_data.rs from Oniguruma's unicode_fold_data.c (#6225).

jq 1.7.1 links Oniguruma 6.9.x, whose case-insensitive matching expands a literal through the
*full* Unicode case folding (`ß` is `ss`, `ﬁ` is `fi`).  The tables below are that library's own
(src/unicode_fold_data.c at tag v6.9.8, Unicode 14.0), not a re-derivation from CaseFolding.txt, so
the entries and their order are the ones the library walks.

Usage:
    curl -sSfL https://raw.githubusercontent.com/kkos/oniguruma/v6.9.8/src/unicode_fold_data.c \
        -o /tmp/unicode_fold_data.c
    python3 -I scripts/gen_onig_fold_data.py /tmp/unicode_fold_data.c > src/jq/onig_fold_data.rs
"""
import re
import sys


def numbers(line):
    line = re.sub(r"/\*.*?\*/", "", line)
    return [int(tok, 16) if tok.startswith("0x") else int(tok) for tok in re.findall(r"0x[0-9a-fA-F]+|\d+", line)]


def section(text, name):
    start = text.index("OnigCodePoint %s[] = {" % name)
    end = text.index("};", start)
    body = text[start:end].split("\n")[1:]
    rows = []
    for line in body:
        if line.strip().startswith("#"):
            continue
        # A multi-line comment's lines carry no numbers once the comment is stripped.
        nums = numbers(line)
        if nums:
            rows.append(nums)
    return rows


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    folds1 = section(text, "OnigUnicodeFolds1")
    folds2 = section(text, "OnigUnicodeFolds2")
    folds3 = section(text, "OnigUnicodeFolds3")

    entries2 = []
    for row in folds2:
        f0, f1, n = row[0], row[1], row[2]
        unfolds = row[3:]
        assert len(unfolds) == n, row
        entries2.append(((f0, f1), unfolds))
    entries3 = []
    for row in folds3:
        f0, f1, f2, n = row[0], row[1], row[2], row[3]
        unfolds = row[4:]
        assert len(unfolds) == n, row
        entries3.append(((f0, f1, f2), unfolds))

    keychars = set()
    for fold, _ in entries2 + entries3:
        keychars.update(fold)

    # Each simple (one-to-one) fold class: its target, then the characters that fold to it.
    key_map = {}
    for row in folds1:
        target, n = row[0], row[1]
        unfolds = row[2:]
        assert len(unfolds) == n, row
        if target in keychars:
            for u in unfolds:
                key_map[u] = target

    def ch(cp):
        return "'\\u{%x}'" % cp

    out = []
    out.append("// @generated by scripts/gen_onig_fold_data.py from Oniguruma v6.9.8 src/unicode_fold_data.c")
    out.append("// (Unicode 14.0). Do not edit by hand; see the script for how to regenerate (#6225).")
    out.append("")
    out.append("/// Two-character folds: the folded pair, and the characters that fold to it, in the library's order.")
    out.append("pub(super) const FOLDS2: &[([char; 2], &[char])] = &[")
    for fold, unfolds in entries2:
        out.append("    ([%s], &[%s])," % (", ".join(ch(c) for c in fold), ", ".join(ch(c) for c in unfolds)))
    out.append("];")
    out.append("")
    out.append("/// Three-character folds, as [`FOLDS2`].")
    out.append("pub(super) const FOLDS3: &[([char; 3], &[char])] = &[")
    for fold, unfolds in entries3:
        out.append("    ([%s], &[%s])," % (", ".join(ch(c) for c in fold), ", ".join(ch(c) for c in unfolds)))
    out.append("];")
    out.append("")
    out.append("/// The one-to-one fold of a character whose fold is a character [`FOLDS2`] or [`FOLDS3`] spells,")
    out.append("/// sorted by the character. A character absent here folds to itself for those tables.")
    out.append("pub(super) const FOLD_KEY: &[(char, char)] = &[")
    for u in sorted(key_map):
        out.append("    (%s, %s)," % (ch(u), ch(key_map[u])))
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
