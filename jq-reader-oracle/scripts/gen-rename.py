#!/usr/bin/env python3
"""Write vendor/rename-<release>.h: one `#define` per global symbol of a vendored jq subset.

    python3 scripts/gen-rename.py            # both releases; needs `cc` and `nm`

build.rs compiles both vendored releases into one binary. They define the same C symbols, so
every translation unit of a release is compiled with `-include vendor/rename-<release>.h`, which
renames each of them to `sjq171_<name>` or `sjq182_<name>`. This script compiles each release's
files the way build.rs does, without the header, and lists the symbols they define with `nm`.
`jq_get_input_cb` is added by hand: util.c calls it and `src/shim.c` defines it.

Run it again after changing a vendored file or build.rs's file list. The
`every_global_symbol_is_renamed` test (tests/oracle.rs) fails when the headers fall behind.
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["jv.c", "jv_alloc.c", "jv_aux.c", "jv_dtoa.c", "jv_dtoa_tsd.c", "jv_parse.c",
           "jv_print.c", "jv_unicode.c", "util.c"]
DECNUMBER = ["decContext.c", "decNumber.c"]
RELEASES = [("1.7.1", "sjq171_", "src"), ("1.8.2", "sjq182_", "vendor")]
DEFINES = ["IEEE_8087=1", "HAVE_MEMMEM=1", "HAVE_STRPTIME=1", "HAVE_PTHREAD=1",
           "HAVE_PTHREAD_KEY_CREATE=1", "HAVE_PTHREAD_ONCE=1", "HAVE_ATEXIT=1", "HAVE___THREAD=1",
           "USE_DECNUM=1", "_GNU_SOURCE=1"]
BY_HAND = ["jq_get_input_cb"]


def symbols(release, dec_parent):
    root = os.path.join(HERE, "vendor", "jq-" + release)
    src = os.path.join(root, "src")
    dec = os.path.join(root, dec_parent)
    files = [os.path.join(src, f) for f in SOURCES] + [os.path.join(dec, "decNumber", f) for f in DECNUMBER]
    names = set()
    with tempfile.TemporaryDirectory() as tmp:
        for i, f in enumerate(files):
            obj = os.path.join(tmp, "%d.o" % i)
            cmd = ["cc", "-c", "-O2", "-w", "-I", src, "-I", dec] + ["-D" + d for d in DEFINES] + [f, "-o", obj]
            subprocess.run(cmd, check=True)
            out = subprocess.run(["nm", "-g", obj], check=True, capture_output=True, text=True).stdout
            for line in out.splitlines():
                parts = line.split()
                # "<addr> <type> <name>"; undefined symbols have no address.
                if len(parts) == 3 and parts[1] not in "Uu":
                    name = parts[2]
                    if sys.platform == "darwin":
                        name = name[1:]  # Mach-O's leading underscore
                    names.add(name)
    return sorted(names | set(BY_HAND))


def main():
    for release, prefix, dec_parent in RELEASES:
        names = symbols(release, dec_parent)
        path = os.path.join(HERE, "vendor", "rename-%s.h" % release)
        with open(path, "w") as fh:
            fh.write("/* Generated by scripts/gen-rename.py; do not edit. Renames every global symbol of\n")
            fh.write(" * the vendored jq %s subset, so that both releases link into one binary. */\n" % release)
            for n in names:
                fh.write("#define %s %s%s\n" % (n, prefix, n))
        print("%s: %d symbols -> %s" % (release, len(names), os.path.relpath(path, HERE)))


if __name__ == "__main__":
    main()
